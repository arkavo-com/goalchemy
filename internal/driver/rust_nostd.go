func init() { Register("rust-nostd", emitRustNoStd) }

// This profile shares Rust's contracts and pure runtime implementations. Keep
// its catalog private to this emission so target selection never mutates Rust.
func rustNoStdCatalog(cat *contracts.Catalog) *contracts.Catalog {
	c := *cat
	c.Targets = make(map[string]*contracts.Target, len(cat.Targets)+1)
	for name, target := range cat.Targets {
		c.Targets[name] = target
	}
	t := *cat.Targets["rust"]
	t.Target = "rust-nostd"
	t.Functions = nil
	for _, f := range cat.Targets["rust"].Functions {
		if noStdContract(f.ID) {
			t.Functions = append(t.Functions, f)
		}
	}
	t.SupportFiles = []string{
		"types/float.rs", "types/bounds.rs", "types/func.rs", "types/heap.rs",
		"types/ints.rs", "types/map.rs", "types/ops.rs", "types/panic.rs",
		"types/program.rs", "types/utf8.rs", "types/value.rs",
		"nostd/owner.rs", "nostd/out.rs",
	}
	t.Harness = nil
	c.Targets[t.Target] = &t
	return &c
}

func noStdContract(id string) bool {
	for _, prefix := range []string{"core.integer.", "core.float.", "core.string.", "core.slice.", "core.map.", "std.errors."} {
		if strings.HasPrefix(id, prefix) {
			return true
		}
	}
	return id == "core.print"
}

func emitRustNoStd(res *Result, out string) []diagnostics.Diagnostic {
	o, err := rust.EmitNoStd(res.IR, symbols(res, "rust-nostd"))
	if err != nil {
		return []diagnostics.Diagnostic{{Code: "GCE007", Severity: diagnostics.Error, Feature: "Rust no_std profile", Message: err.Error(), Remedy: "Use sequential code and owned values without recover, or select -target rust."}}
	}
	refs, files, ds := link.Plan(res.Catalog, "rust-nostd", o.Contracts)
	if len(ds) > 0 {
		return ds
	}
	runtimeFiles, err := link.CopyRuntime(res.Catalog, "rust-nostd", files, out, "src/rt", false)
	if err != nil {
		return emitErr("GCE005", err.Error())
	}
	var mod strings.Builder
	mod.WriteString("// Code generated by goalchemy. DO NOT EDIT.\nuse super::*;\n#[macro_use]\n#[path = \"nostd/owner.rs\"]\nmod owner;\npub use owner::*;\n")
	for _, f := range files {
		if f == "nostd/owner.rs" {
			continue
		}
		name := strings.TrimSuffix(path.Base(f), ".rs")
		fmt.Fprintf(&mod, "#[path = %q]\npub mod %s;\npub use %s::*;\n", f, name, name)
	}
	gen := map[string][]byte{
		"src/rt/mod.rs": []byte(mod.String()),
		"Cargo.toml":    []byte(rustNoStdCargo),
		"build.rs":      []byte("fn main() { println!(\"cargo:rustc-check-cfg=cfg(goalchemy_nostd)\"); println!(\"cargo:rustc-cfg=goalchemy_nostd\"); }\n"),
		"README.md":     []byte(rustNoStdReadme),
	}
	if !res.IR.Library {
		gen["run.sh"] = []byte(rustNoStdRun)
		gen["host.rs"] = []byte(rustNoStdHost)
	}
	names, err := writeSourceArtifacts(out, o.Files)
	if err != nil {
		return emitErr("GCE005", err.Error())
	}
	for name, data := range gen {
		if err := link.WriteFile(out, name, data); err != nil {
			return emitErr("GCE005", err.Error())
		}
		names = append(names, name)
	}
	sort.Strings(names)
	if res.ObserveAPI != nil {
		res.ObserveAPI(o.API)
	}
	if err := link.WriteManifest(out, res.Catalog, "rust-nostd", refs, runtimeFiles, names, res.Program, o.Packages...); err != nil {
		return emitErr("GCE005", err.Error())
	}
	return nil
}

const rustNoStdCargo = `[package]
name = "goalchemy-out"
version = "0.1.0"
edition = "2021"
rust-version = "1.85"
autobins = false

[lib]
path = "src/lib.rs"

[profile.release]
opt-level = "s"
panic = "abort"
codegen-units = 1

[profile.dev]
panic = "abort"
`
const rustNoStdRun = `#!/bin/sh
set -e
cd "$(dirname "$0")"
rustc --edition 2021 --crate-name goalchemy_out --crate-type rlib --cfg goalchemy_nostd -C panic=abort -C opt-level=s -C debuginfo=0 -C codegen-units=1 src/lib.rs -o libgoalchemy_out.rlib >&2
rustc --edition 2021 -C panic=abort -C opt-level=s -C debuginfo=0 host.rs --extern goalchemy_out=libgoalchemy_out.rlib -o main >&2
exec ./main
`
const rustNoStdHost = `// Optional host smoke runner; the generated library itself never links std.
use std::io::Write;
fn write(bytes: &[u8]) { let _ = std::io::stderr().write_all(bytes); }
fn main() {
    let options = goalchemy_out::RuntimeOptions {
        output: Some(write),
        gc_threshold: std::env::var("GOALCHEMY_GC_THRESHOLD").ok().and_then(|s| s.parse().ok()).unwrap_or(256),
        ..Default::default()
    };
    let result = goalchemy_out::run(options).expect("runtime entry");
    if std::env::var_os("GOALCHEMY_HEAP_STATS").is_some() {
        let h = result.heap;
        eprintln!("heap: peak {} live {} collections {}", h.peak_objects, h.live_objects, h.collections);
    }
}
`
const rustNoStdReadme = `# Generated Rust no_std + alloc library

Build with cargo build --release --lib --target <installed-target>.
The application supplies a global allocator, panic handler, and entry point.
The target must support 8-bit compare-and-exchange atomics. No dependencies,
OS, TLS, worker threads, or large reserved stacks are included in the library.

Programs expose run(RuntimeOptions). Libraries expose synchronous owned-value
functions with RuntimeOptions as their final argument. Each call returns
Result<CallResult<T>, NoStdError>, initializes fresh source globals, and releases
all internal heap allocations on return. Concurrent/reentrant calls return Busy.
CallResult contains the owned value and heap statistics just before cleanup.

RuntimeOptions defaults to a minimum of 256 allocation units between collections
(adapting to the live object count) and a source call depth limit of 64. Byte buffers add one allocation unit per KiB. These are
collection/recursion controls, not hard byte or stack limits. Live data, frames,
strings, output values, and collector scratch space also consume memory.
Tune these options and the embedding allocator to the device's actual budget.
Print output goes to the optional function pointer; None discards it.

Panics use the application's panic handler. There is no Go panic recovery or
panic-path defer execution. Normal-return defer is supported. recover,
concurrency, host capabilities, and exported handles/streams are rejected.
An exported trailing Go error becomes NoStdError::Source with its message.

For package main, sh run.sh compiles the no_std library and an optional std host
smoke runner. The host runner supports GOALCHEMY_GC_THRESHOLD and
GOALCHEMY_HEAP_STATS; embedded applications configure RuntimeOptions directly.
`
