package py

import (
	"bytes"
	"fmt"
	"go/token"
	"sort"
	"strings"

	"github.com/eugenioenko/goalchemy/internal/emit/artifact"
	"github.com/eugenioenko/goalchemy/internal/ir"
	"github.com/eugenioenko/goalchemy/internal/naming"
)

// Emit keeps one naming and representation index while routing actual native
// declarations into source-owned modules. Canonical helpers are a leaf; main
// binds descriptors after package functions and their live storage have loaded.
func Emit(p *ir.Program, symbols map[string]string) (*Output, error) {
	layout, err := artifact.NewLayout(p)
	if err != nil {
		return nil, err
	}
	e := &emitter{p: p, names: naming.New(p), symbols: symbols, contracts: map[string]bool{}, classes: map[*ir.Type]string{},
		tds: map[*ir.Type]string{}, seenHelp: map[*ir.Type]bool{}, locations: map[string]string{}, imports: map[string]map[string]bool{}}
	bodies := map[string]*bytes.Buffer{"_shared.py": {}, "main.py": {}}
	owners := map[string]string{}
	paths := []string{"_shared.py"}
	for _, pkg := range layout.Packages {
		file := layout.Stem(pkg.Path) + ".py"
		paths = append(paths, file)
		bodies[file] = &bytes.Buffer{}
		owners[file] = pkg.Path
	}
	paths = append(paths, "main.py")
	location := func(owner string) string {
		if owner == "" {
			return "_shared.py"
		}
		return layout.Stem(owner) + ".py"
	}
	for _, f := range p.Funcs {
		file := location(f.Pkg)
		if f == p.Init || f == p.Entry {
			file = "main.py"
		}
		e.locations[f.Sym] = file
	}
	for _, g := range p.Globals {
		e.locations[g.Sym] = location(g.Pkg)
	}
	for _, t := range p.Types.All {
		if t.Boxed {
			e.td(t)
		}
	}
	for _, g := range p.Globals {
		file := e.locations[g.Sym]
		e.current = file
		zero := e.zero(g.Type)
		if g.AddrTaken && !g.Type.IsAggregate() {
			zero = "rt.Cell(" + zero + ")"
		}
		fmt.Fprintf(bodies[file], "%s%s = %s\n", position(g.Pos), e.names.Symbol(g.Sym), zero)
	}
	for _, f := range p.Funcs {
		file := e.locations[f.Sym]
		e.current = file
		bodies[file].WriteString(e.function(f))
		fmt.Fprintf(bodies[file], "%s._fid = %d\n\n", e.names.Symbol(f.Sym), f.ID)
	}
	e.current = "main.py"
	// Public boundary discovery can add descriptor/helper uses, so retain the
	// original library-before-descriptor discovery order.
	var library string
	if p.Library {
		library, err = e.library()
		if err != nil {
			return nil, err
		}
	}
	e.typeDescs(bodies["main.py"])
	if p.Library {
		bodies["main.py"].WriteString("\n" + library)
	} else if p.Cooperative {
		e.use("core.task.spawn")
		start := e.symbol(p.Entry.Sym) + "()"
		if !p.Entry.MaySuspend {
			start = "rt.sync(lambda: (" + e.symbol(p.Entry.Sym) + "(), [])[1])"
		}
		run := "rt.run_main(" + start + ")"
		if ir.HostEntry(e.contracts) {
			run = "runHost()"
		}
		fmt.Fprintf(bodies["main.py"], "\ndef runHost():\n    return rt.run_main_host(lambda: %s)\n\nif __name__ == \"__main__\":\n    %s\n", start, run)
	} else {
		fmt.Fprintf(bodies["main.py"], "\n\ndef _entry():\n    %s()\n", e.symbol(p.Init.Sym))
		if p.Main != nil {
			fmt.Fprintf(bodies["main.py"], "    %s()\n", e.symbol(p.Main.Sym))
		}
		bodies["main.py"].WriteString("\n\nif __name__ == \"__main__\":\n    rt.main(_entry)\n")
	}
	e.current = "_shared.py"
	e.flushHelpers()
	if len(e.imports["_shared.py"]) != 0 {
		return nil, fmt.Errorf("canonical Python support references a source module")
	}
	helpers := []string{"_types"}
	for _, name := range e.classes {
		helpers = append(helpers, name)
	}
	for typ := range e.seenHelp {
		if typ.Kind == ir.KArray {
			for _, prefix := range []string{"zero_", "clone_", "set_", "eq_", "key_"} {
				helpers = append(helpers, e.names.Type(typ, prefix))
			}
		}
	}
	sort.Strings(helpers)
	var files []artifact.File
	for _, file := range paths {
		var source bytes.Buffer
		source.WriteString("# Code generated by goalchemy. DO NOT EDIT.\n# flake8: noqa\n")
		if p.Library {
			source.WriteString("from . import rt\n")
		} else {
			source.WriteString("import rt\n")
		}
		if file == "_shared.py" {
			source.WriteString("\nclass _Types:\n    pass\n\n_types = _Types()\n\n")
			source.Write(e.helperOut.Bytes())
		} else {
			from := "_shared"
			if p.Library {
				from = "." + from
			}
			fmt.Fprintf(&source, "from %s import %s\n", from, strings.Join(helpers, ", "))
		}
		var dependencies []string
		for dependency := range e.imports[file] {
			dependencies = append(dependencies, dependency)
		}
		sort.Strings(dependencies)
		for _, dependency := range dependencies {
			module := strings.TrimSuffix(dependency, ".py")
			if p.Library {
				fmt.Fprintf(&source, "from . import %s as %s\n", module, moduleName(dependency))
			} else {
				fmt.Fprintf(&source, "import %s as %s\n", module, moduleName(dependency))
			}
		}
		source.WriteByte('\n')
		source.Write(bodies[file].Bytes())
		src, lines := e.resolveMarkers(source.String())
		if e.p.NoLineDirectives {
			lines = nil
		}
		files = append(files, artifact.File{Path: file, Source: []byte(src), Owner: owners[file], Lines: lines})
	}
	var contracts []string
	for contract := range e.contracts {
		contracts = append(contracts, contract)
	}
	sort.Strings(contracts)
	return &Output{Files: files, Packages: layout.PackageFiles(files), Contracts: contracts}, nil
}

func moduleName(file string) string { return "_module_" + strings.TrimSuffix(file, ".py") }
func position(pos token.Pos) string {
	if !pos.IsValid() {
		return ""
	}
	return fmt.Sprintf("%s%d\x00", marker, pos)
}
