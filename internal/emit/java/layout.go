package java

import (
	"bytes"
	"fmt"
	"go/token"
	"sort"

	"github.com/eugenioenko/goalchemy/internal/emit/artifact"
	"github.com/eugenioenko/goalchemy/internal/ir"
	"github.com/eugenioenko/goalchemy/internal/naming"
)

const supportClass = "_GoalchemySupport"

// Emit routes storage, methods and frames directly into source-package holder
// classes while retaining one whole-program naming/type/effect index. Support
// contains canonical representations but no eager references to holder state.
func Emit(p *ir.Program, symbols map[string]string) (*Output, error) {
	layout, err := artifact.NewLayout(p)
	if err != nil {
		return nil, err
	}
	e := &emitter{p: p, names: naming.New(p, NameRules(p)), symbols: symbols, contracts: map[string]bool{}, classes: map[*ir.Type]string{},
		tds: map[*ir.Type]string{}, seenHelp: map[*ir.Type]bool{}, locations: map[string]string{}}
	entry := e.mainClass()
	bodies := map[string]*bytes.Buffer{supportClass: {}, entry: {}}
	owners := map[string]string{}
	classes := []string{supportClass}
	for _, pkg := range layout.Packages {
		class := layout.Stem(pkg.Path)
		classes = append(classes, class)
		bodies[class] = &bytes.Buffer{}
		owners[class] = pkg.Path
	}
	classes = append(classes, entry)
	location := func(owner string) string {
		if owner == "" {
			return supportClass
		}
		return layout.Stem(owner)
	}
	for _, function := range p.Funcs {
		class := location(function.Pkg)
		if function == p.Init || function == p.Entry {
			class = entry
		}
		e.locations[function.Sym] = class
	}
	for _, global := range p.Globals {
		e.locations[global.Sym] = location(global.Pkg)
	}
	for _, typ := range p.Types.All {
		if typ.Boxed {
			e.td(typ)
		}
	}
	for _, global := range p.Globals {
		class := e.locations[global.Sym]
		e.current = class
		typ, zero := e.jt(global.Type), e.zero(global.Type)
		if global.AddrTaken && !global.Type.IsAggregate() {
			typ = "Cell"
			zero = "new Cell(" + zero + ")"
		}
		fmt.Fprintf(bodies[class], "%s    static %s %s = %s;\n", position(global.Pos), typ, e.names.Symbol(global.Sym), zero)
	}
	for _, function := range p.Funcs {
		class := e.locations[function.Sym]
		e.current = class
		e.frames.Reset()
		bodies[class].WriteString(e.function(function))
		bodies[class].Write(e.frames.Bytes())
	}
	e.current = entry
	// Assign the shared descriptors only in the central class initializer. The
	// superclass has finished loading, and method lambdas defer holder access
	// until the source initializer or public API calls run.
	bodies[entry].WriteString("    static {\n")
	e.typeDescs(bodies[entry])
	bodies[entry].WriteString("    }\n\n")
	if p.Library {
		library, err := e.library()
		if err != nil {
			return nil, &LibraryBoundaryError{err.Error()}
		}
		bodies[entry].WriteString(library)
	} else if p.Cooperative {
		e.use("core.task.spawn")
		start := e.symbol(p.Entry.Sym) + "()"
		if !p.Entry.MaySuspend {
			start = "TaskSpawn.sync(() -> { " + e.symbol(p.Entry.Sym) + "(); return new Object[0]; })"
		}
		run := "TaskSpawn.runMain(" + start + ");"
		if ir.HostEntry(e.contracts) {
			run = "runHost();\n        System.out.flush();\n        System.exit(0);"
		}
		fmt.Fprintf(bodies[entry], "    public static void runHost() {\n        TaskSpawn.runMainHost(() -> %s);\n    }\n\n    public static void main(String[] args) {\n        %s\n    }\n", start, run)
	} else {
		fmt.Fprintf(bodies[entry], "    public static void main(String[] args) {\n        Program.main(() -> {\n            %s();\n", e.symbol(p.Init.Sym))
		if p.Main != nil {
			fmt.Fprintf(bodies[entry], "            %s();\n", e.symbol(p.Main.Sym))
		}
		bodies[entry].WriteString("        });\n    }\n")
	}
	e.current = supportClass
	e.flushHelpers()
	var descriptors []*ir.Type
	for typ := range e.tds {
		descriptors = append(descriptors, typ)
	}
	sort.Slice(descriptors, func(i, j int) bool { return descriptors[i].ID < descriptors[j].ID })
	var files []artifact.File
	for _, class := range classes {
		var source bytes.Buffer
		source.WriteString("// Code generated by goalchemy. DO NOT EDIT.\n")
		if p.Library {
			source.WriteString("package io.goalchemy.generated;\nimport io.goalchemy.runtime.*;\n")
		} else {
			source.WriteString("import rt.*;\n")
		}
		source.WriteString("\n@SuppressWarnings({\"unchecked\", \"unused\", \"rawtypes\"})\n")
		switch class {
		case supportClass:
			fmt.Fprintf(&source, "class %s {\n", class)
			source.WriteString(mainHelpers)
			if e.contracts["core.task.spawn"] {
				source.WriteString(spawnHelper)
			}
			source.Write(e.helperOut.Bytes())
			for _, typ := range descriptors {
				fmt.Fprintf(&source, "    static TypeDesc %s;\n", e.tds[typ])
			}
		case entry:
			fmt.Fprintf(&source, "public final class %s extends %s {\n", class, supportClass)
		default:
			fmt.Fprintf(&source, "final class %s extends %s {\n", class, supportClass)
		}
		source.Write(bodies[class].Bytes())
		source.WriteString("}\n")
		src, lines := e.resolveMarkers(source.String())
		if e.p.NoLineDirectives {
			lines = nil
		}
		files = append(files, artifact.File{Path: class + ".java", Source: []byte(src), Owner: owners[class], Lines: lines})
	}
	var contracts []string
	for contract := range e.contracts {
		contracts = append(contracts, contract)
	}
	sort.Strings(contracts)
	return &Output{Files: files, Packages: layout.PackageFiles(files), Contracts: contracts}, nil
}

func position(pos token.Pos) string {
	if !pos.IsValid() {
		return ""
	}
	return fmt.Sprintf("%s%d\x00", marker, pos)
}
