package csharp

import (
	"bytes"
	"fmt"
	"go/token"
	"sort"

	"github.com/eugenioenko/goalchemy/internal/emit/artifact"
	"github.com/eugenioenko/goalchemy/internal/ir"
	"github.com/eugenioenko/goalchemy/internal/naming"
)

// Emit writes native partial class declarations directly to their source owner.
// Every file shares the same GoProgram scope and naming/type/effect index.
func Emit(p *ir.Program, symbols map[string]string) (*Output, error) {
	layout, err := artifact.NewLayout(p)
	if err != nil {
		return nil, err
	}
	e := &emitter{p: p, names: naming.New(p, NameRules(p)), symbols: symbols, contracts: map[string]bool{}, classes: map[*ir.Type]string{},
		tds: map[*ir.Type]string{}, seenHelp: map[*ir.Type]bool{}, layout: layout, helpers: map[string]*bytes.Buffer{"": {}}}
	bodies := map[string]*bytes.Buffer{"": {}}
	for _, pkg := range layout.Packages {
		bodies[pkg.Path] = &bytes.Buffer{}
		e.helpers[pkg.Path] = &bytes.Buffer{}
	}
	for _, typ := range p.Types.All {
		if typ.Boxed {
			e.td(typ)
		}
	}
	for _, global := range p.Globals {
		typ, zero := e.jt(global.Type), e.zero(global.Type)
		if global.AddrTaken && !global.Type.IsAggregate() {
			typ = "Cell"
			zero = "new Cell(" + zero + ")"
		}
		fmt.Fprintf(bodies[global.Pkg], "%s    static %s %s = %s;\n", position(global.Pos), typ, e.symbol(global.Sym), zero)
	}
	for _, function := range p.Funcs {
		owner := function.Pkg
		if function == p.Init || function == p.Entry {
			owner = ""
		}
		e.frames.Reset()
		bodies[owner].WriteString(e.function(function))
		bodies[owner].Write(e.frames.Bytes())
	}
	var descriptors bytes.Buffer
	e.typeDescs(&descriptors)
	if p.Library {
		library, err := e.library()
		if err != nil {
			return nil, &LibraryBoundaryError{err.Error()}
		}
		bodies[""].WriteString(library)
	} else if p.Cooperative {
		e.use("core.task.spawn")
		start := e.symbol(p.Entry.Sym) + "()"
		if !p.Entry.MaySuspend {
			start = "R.sync(() => { " + e.symbol(p.Entry.Sym) + "(); return Array.Empty<object>(); })"
		}
		run := "R.runMain(" + start + ");"
		if ir.HostEntry(e.contracts) {
			run = "runHost().GetAwaiter().GetResult();\n        System.Environment.Exit(0);"
		}
		fmt.Fprintf(bodies[""], "    public static System.Threading.Tasks.Task runHost() {\n        return R.runMainHost(() => %s);\n    }\n\n    public static void Main(string[] _args) {\n        %s\n    }\n", start, run)
	} else {
		fmt.Fprintf(bodies[""], "    public static void Main(string[] _args) {\n        Program.main(() => {\n            %s();\n", e.symbol(p.Init.Sym))
		if p.Main != nil {
			fmt.Fprintf(bodies[""], "            %s();\n", e.symbol(p.Main.Sym))
		}
		bodies[""].WriteString("        });\n    }\n")
	}
	e.flushHelpers()
	preamble := "// Code generated by goalchemy. DO NOT EDIT.\nusing System;\nusing System.Collections.Generic;\nusing Rt;\n\n"
	if p.Library {
		preamble += "namespace Goalchemy.Generated;\n"
	}
	preamble += "public static partial class GoProgram {\n"
	var files []artifact.File
	write := func(path, owner string, body []byte) {
		source, lines := e.resolveMarkers(preamble + string(body) + "}\n")
		if e.p.NoLineDirectives {
			lines = nil
		}
		files = append(files, artifact.File{Path: path, Owner: owner, Source: []byte(source), Lines: lines})
	}
	var shared bytes.Buffer
	shared.WriteString(mainHelpers)
	if e.contracts["core.task.spawn"] {
		shared.WriteString(spawnHelper)
	}
	shared.Write(e.helpers[""].Bytes())
	shared.Write(descriptors.Bytes())
	write("shared.cs", "", shared.Bytes())
	for _, pkg := range layout.Packages {
		var body bytes.Buffer
		body.Write(e.helpers[pkg.Path].Bytes())
		body.Write(bodies[pkg.Path].Bytes())
		write(layout.Stem(pkg.Path)+".cs", pkg.Path, body.Bytes())
	}
	write("Main.cs", "", bodies[""].Bytes())
	var contracts []string
	for contract := range e.contracts {
		contracts = append(contracts, contract)
	}
	sort.Strings(contracts)
	return &Output{API: e.api, Files: files, Packages: layout.PackageFiles(files), Contracts: contracts}, nil
}

func position(pos token.Pos) string {
	if !pos.IsValid() {
		return ""
	}
	return fmt.Sprintf("%s%d\x00", marker, pos)
}
