// Emit routes native Rust items directly into source-package modules. The
// generated parent owns initialization/API and one shared runtime/root graph.
func Emit(p *ir.Program, symbols map[string]string) (*Output, error) {
	return emit(p, symbols, false)
}

func EmitNoStd(p *ir.Program, symbols map[string]string) (*Output, error) {
	if err := validateNoStd(p); err != nil {
		return nil, err
	}
	return emit(p, symbols, true)
}

func emit(p *ir.Program, symbols map[string]string, noStd bool) (*Output, error) {
	layout, err := artifact.NewLayout(p)
	if err != nil {
		return nil, err
	}
	rules := NameRules(p)
	if noStd {
		rules = NoStdNameRules(p)
	}
	e := &emitter{p: p, noStd: noStd, names: naming.New(p, rules), symbols: symbols, contracts: map[string]bool{}, tds: map[*ir.Type]bool{},
		seenHelp: map[*ir.Type]bool{}, zeros: map[*ir.Type]bool{}, externs: map[string]*ir.Extern{}, layout: layout,
		locations: map[string]string{}, helpers: map[string]*bytes.Buffer{"shared": {}}}
	bodies := map[string]*bytes.Buffer{"": {}}
	for _, pkg := range layout.Packages {
		scope := layout.Stem(pkg.Path)
		bodies[scope] = &bytes.Buffer{}
		e.helpers[scope] = &bytes.Buffer{}
	}
	for _, function := range p.Funcs {
		scope := layout.Stem(function.Pkg)
		if function == p.Init || function == p.Entry {
			scope = ""
		}
		e.locations[function.Sym] = scope
	}
	for index, global := range p.Globals {
		scope := layout.Stem(global.Pkg)
		e.locations[global.Sym] = scope
		e.current = scope
		// Slots remain in the runtime's single traced globals vector. Package
		// modules own their slot identities and zero-storage initializer.
		fmt.Fprintf(bodies[scope], "%s%sconst %s: usize = %d;\n", position(global.Pos), e.visibility(), e.names.Symbol(global.Sym), index)
	}
	for _, typ := range p.Types.All {
		if typ.Boxed {
			e.tds[typ] = true
		}
	}
	for _, function := range p.Funcs {
		e.current = e.locations[function.Sym]
		bodies[e.current].WriteString(e.function(function))
		bodies[e.current].WriteString(e.wrapper(function))
	}
	for _, pkg := range layout.Packages {
		e.current = layout.Stem(pkg.Path)
		body := bodies[e.current]
		body.WriteString("pub(super) fn _init_zero_package() {\n")
		for _, global := range p.Globals {
			if global.Pkg == pkg.Path {
				zero := e.zero(global.Type)
				if scalarGlobal(global) {
					zero = "cellv(" + zero + ")"
				}
				fmt.Fprintf(body, "    gs(%s, %s);\n", e.symbol(global.Sym, ""), zero)
			}
		}
		body.WriteString("}\n\n")
	}
	e.current = ""
	root := bodies[""]
	root.WriteString("fn _init_zero_globals() {\n")
	for _, global := range p.Globals {
		if global.Pkg == "" {
			zero := e.zero(global.Type)
			if scalarGlobal(global) {
				zero = "cellv(" + zero + ")"
			}
			fmt.Fprintf(root, "    gs(%s, %s);\n", e.symbol(global.Sym, ""), zero)
		}
	}
	for _, pkg := range layout.Packages {
		fmt.Fprintf(root, "    %s::_init_zero_package();\n", layout.Stem(pkg.Path))
	}
	root.WriteString("}\n\n")
	if p.Library {
		library, err := e.library()
		if err != nil {
			return nil, err
		}
		root.WriteString(library)
	} else if p.Cooperative {
		e.use("core.task.spawn")
		root.WriteString("fn _entry_frame() -> V {\n")
		if p.Entry.MaySuspend {
			fmt.Fprintf(root, "    %s()\n", e.symbol(p.Entry.Sym, "f_"))
		} else {
			fmt.Fprintf(root, "    sync_frame(func(-1, %s, Vec::new()), Vec::new(), 0)\n", e.symbol(p.Entry.Sym, "w_"))
		}
		run := fmt.Sprintf("run_main(%d, _init_zero_globals, _entry_frame)", len(p.Globals))
		if ir.HostEntry(e.contracts) {
			run = "report_host_result(run_host())"
		}
		fmt.Fprintf(root, "}\n\npub fn run_host() -> Result<(), HostError> {\n    run_main_host(%d, _init_zero_globals, _entry_frame)\n}\n\nfn main() {\n    %s\n}\n", len(p.Globals), run)
	} else {
		fmt.Fprintf(root, "fn _entry() {\n    %s();\n", e.symbol(p.Init.Sym, "f_"))
		if p.Main != nil {
			fmt.Fprintf(root, "    %s();\n", e.symbol(p.Main.Sym, "f_"))
		}
		if noStd {
			fmt.Fprintf(root, "}\n\npub fn run(options: RuntimeOptions) -> Result<CallResult<()>, NoStdError> {\n    rt::invoke(options, %d, _init_zero_globals, || { _entry(); Ok(()) })\n}\n", len(p.Globals))
		} else {
			fmt.Fprintf(root, "}\n\nfn main() {\n    program_main(%d, _init_zero_globals, _entry)\n}\n", len(p.Globals))
		}
	}
	e.externWrappers(root)
	e.current = "shared"
	var shared bytes.Buffer
	e.typeDescs(&shared)
	e.flushHelpers()
	var files []artifact.File
	write := func(path, owner, preamble string, body []byte) {
		source, lines := e.resolveMarkers(preamble + string(body))
		if e.p.NoLineDirectives {
			lines = nil
		}
		files = append(files, artifact.File{Path: path, Owner: owner, Source: []byte(source), Lines: lines})
	}
	modulePreamble := "// Code generated by goalchemy. DO NOT EDIT.\nuse super::*;\n\n"
	var support bytes.Buffer
	support.Write(e.helpers["shared"].Bytes())
	support.Write(shared.Bytes())
	write("src/shared.rs", "", modulePreamble, support.Bytes())
	for _, pkg := range layout.Packages {
		scope := layout.Stem(pkg.Path)
		var body bytes.Buffer
		body.Write(e.helpers[scope].Bytes())
		body.Write(bodies[scope].Bytes())
		write("src/"+scope+".rs", pkg.Path, modulePreamble, body.Bytes())
	}
	var preamble bytes.Buffer
	preamble.WriteString("// Code generated by goalchemy. DO NOT EDIT.\n")
	if noStd {
		preamble.WriteString("#![no_std]\n#![allow(warnings)]\n#[macro_use] extern crate alloc;\nuse alloc::{boxed::Box, vec::Vec, string::{String, ToString}};\npub use rt::{RuntimeOptions, CallResult, HeapStats, NoStdError};\n")
	}
	if !noStd {
		preamble.WriteString("#![allow(warnings)]\n")
	}
	preamble.WriteString("\n#[path = \"rt/mod.rs\"]\nmod rt;\nuse rt::*;\n\n#[path = \"shared.rs\"]\nmod shared;\n")
	for _, pkg := range layout.Packages {
		scope := layout.Stem(pkg.Path)
		fmt.Fprintf(&preamble, "#[path = %q]\nmod %s;\n", scope+".rs", scope)
	}
	entry := "src/main.rs"
	if p.Library || noStd {
		entry = "src/lib.rs"
	}
	write(entry, "", preamble.String()+"\n", root.Bytes())
	var contracts []string
	for contract := range e.contracts {
		contracts = append(contracts, contract)
	}
	sort.Strings(contracts)
	return &Output{API: e.api, Files: files, Packages: layout.PackageFiles(files), Contracts: contracts}, nil
}

func position(pos token.Pos) string {
	if !pos.IsValid() {
		return ""
	}
	return fmt.Sprintf("%s%d\x00", marker, pos)
}

func (e *emitter) visibility() string {
	if e.current == "" {
		return ""
	}
	return "pub(super) "
}

func (e *emitter) reference(scope, name string) string {
	if scope == e.current {
		return name
	}
	if scope != "" {
		name = scope + "::" + name
	}
	if e.current != "" {
		name = "super::" + name
	}
	return name
}

func (e *emitter) symbol(sym, prefix string) string {
	return e.reference(e.locations[sym], e.fnName(sym, prefix))
}

func (e *emitter) helperScope(t *ir.Type) string {
	if owner := e.layout.RepresentationOwner(t); owner != "" {
		return e.layout.Stem(owner)
	}
	return "shared"
}

func (e *emitter) helper(t *ir.Type, prefix string) string {
	return e.reference(e.helperScope(t), e.names.Type(t.U(), prefix))
}

// fnName names the item of kind prefix (f_, w_, a_, st_, rs_) generated for
// a function, or the symbol itself without a prefix.
func (e *emitter) fnName(sym, prefix string) string {
	if prefix == "" {
		return e.names.Symbol(sym)
	}
	return e.names.Derived(strings.TrimSuffix(prefix, "_"), e.names.Symbol(sym))
}
