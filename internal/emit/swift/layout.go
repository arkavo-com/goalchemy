package swift

import (
	"bytes"
	"fmt"
	"go/token"
	"sort"
	"strconv"

	"github.com/eugenioenko/goalchemy/internal/emit/artifact"
	"github.com/eugenioenko/goalchemy/internal/ir"
	"github.com/eugenioenko/goalchemy/internal/naming"
)

// Emit routes source declarations directly into native files within one Swift
// module, retaining one type table and the existing central entry point.
func Emit(p *ir.Program, symbols map[string]string) (*Output, error) {
	layout, err := artifact.NewLayout(p)
	if err != nil {
		return nil, err
	}
	e := &emitter{p: p, names: naming.New(p, NameRules(p)), contracts: map[string]bool{}, symbols: symbols}
	bodies := map[string]*bytes.Buffer{"": {}}
	for _, pkg := range layout.Packages {
		bodies[pkg.Path] = &bytes.Buffer{}
	}
	var shared bytes.Buffer
	e.types(&shared)
	for _, global := range p.Globals {
		fmt.Fprintf(bodies[global.Pkg], "%slet %s = GGlobalCell(GTypes.zero(%d))\n", position(global.Pos), e.names.Symbol(global.Sym), global.Type.ID)
	}
	for _, function := range p.Funcs {
		owner := function.Pkg
		if function == p.Init || function == p.Entry {
			owner = ""
		}
		bodies[owner].WriteString(e.function(function))
	}
	root := bodies[""]
	root.WriteString("func _gSetupMethods() {\n")
	for _, typ := range p.Types.All {
		for _, method := range typ.MethodSet {
			fmt.Fprintf(root, "    GTypes.table[%d].methods[%s] = %s\n", typ.ID, quote(method.ID), e.functionValue(method.Func, ""))
		}
	}
	root.WriteString("}\n")
	entryName := "main.swift"
	if p.Library {
		entryName = "Generated.swift"
		api, err := e.library()
		if err != nil {
			return nil, err
		}
		root.WriteString(api)
	} else {
		entry := p.Entry
		if entry == nil {
			entry = p.Main
		}
		root.WriteString("_ = _gTypeRegistration\n_gSetupMethods()\nGMain {\n    do {\n        let _owner = GOwner(host: " + strconv.FormatBool(ir.HostEntry(e.contracts)) + ")\n")
		if p.Entry == nil && p.Init != nil {
			fmt.Fprintf(root, "        _ = try _owner.run(%s([], []))\n", e.names.Symbol(p.Init.Sym))
		}
		if entry != nil {
			fmt.Fprintf(root, "        _ = try _owner.run(%s([], []))\n", e.names.Symbol(entry.Sym))
		}
		root.WriteString("    } catch { GReport(error) }\n}\n")
	}
	var files []artifact.File
	write := func(path, owner string, body []byte) {
		source, lines := e.markers("// Code generated by Goalchemy. DO NOT EDIT.\nimport Foundation\n\n" + string(body))
		if e.p.NoLineDirectives {
			lines = nil
		}
		files = append(files, artifact.File{Path: path, Owner: owner, Source: []byte(source), Lines: lines})
	}
	write("shared.swift", "", shared.Bytes())
	for _, pkg := range layout.Packages {
		write(layout.Stem(pkg.Path)+".swift", pkg.Path, bodies[pkg.Path].Bytes())
	}
	write(entryName, "", root.Bytes())
	var contracts []string
	for contract := range e.contracts {
		contracts = append(contracts, contract)
	}
	sort.Strings(contracts)
	return &Output{Files: files, Packages: layout.PackageFiles(files), Contracts: contracts}, nil
}

func position(pos token.Pos) string {
	if !pos.IsValid() {
		return ""
	}
	return fmt.Sprintf("%s%d\x00", marker, pos)
}
