// Output contains package-owned files in one native Go package.
type Output struct {
	Files     []artifact.File
	Packages  []artifact.PackageFiles
	Contracts []string
}

type emitter struct {
	p           *ir.Program
	names       *naming.Names
	outDir      string
	symbols     map[string]string
	typeNames   map[*ir.Type]string
	publicTypes map[*ir.Type]string
	abi         *ir.LibraryABI
	methodNames map[string]string
	syms        map[string]bool
	contracts   map[string]bool
	buf         *bytes.Buffer
	layout      *artifact.Layout
	files       map[string]*bytes.Buffer
	owners      map[string]string
	closures    map[*ir.Func]bool
}

// Emit generates source-package-owned files; outDir anchors source positions.
func Emit(p *ir.Program, outDir string, symbols map[string]string) (*Output, error) {
	layout, err := artifact.NewLayout(p)
	if err != nil {
		return nil, err
	}
	e := &emitter{p: p, names: naming.New(p), outDir: outDir, symbols: symbols, typeNames: map[*ir.Type]string{}, syms: map[string]bool{}, contracts: map[string]bool{}, closures: map[*ir.Func]bool{}, layout: layout, files: map[string]*bytes.Buffer{}, owners: map[string]string{}}
	e.selectFile("main.go", "")
	for _, f := range p.Funcs {
		if f.Closure {
			e.closures[f] = true
		}
	}
	if p.Library {
		if err := e.libraryNames(); err != nil {
			return nil, &LibraryBoundaryError{Message: err.Error()}
		}
	}
	e.nameTypes()
	e.typeDecls()
	e.globals()
	for _, f := range p.Funcs {
		if f.Closure && !f.MaySuspend {
			continue
		}
		if f.Pkg != "" {
			e.selectPackage(f.Pkg)
		} else if f == p.Init || f == p.Entry {
			e.selectFile("main.go", "")
		} else {
			e.selectFile("shared.go", "")
		}
		e.function(f)
	}
	e.selectFile("main.go", "")
	if p.Library {
		if err := e.library(); err != nil {
			return nil, &LibraryBoundaryError{Message: err.Error()}
		}
	} else {
		e.entry()
	}
	pkg := "main"
	if p.Library {
		pkg = "generated"
	}
	var paths []string
	for name := range e.files {
		paths = append(paths, name)
	}
	sort.Strings(paths)
	output := &Output{}
	for _, name := range paths {
		src, lines, err := e.sourceFile(name, pkg)
		output.Files = append(output.Files, artifact.File{Path: name, Source: src, Owner: e.owners[name], Lines: lines})
		if err != nil {
			return output, err
		}
	}
	for c := range e.contracts {
		output.Contracts = append(output.Contracts, c)
	}
	sort.Strings(output.Contracts)
	output.Packages = layout.PackageFiles(output.Files)
	return output, nil
}

func (e *emitter) selectFile(name, owner string) {
	if e.files[name] == nil {
		e.files[name] = &bytes.Buffer{}
	}
	e.buf, e.owners[name] = e.files[name], owner
}

func (e *emitter) selectPackage(owner string) {
	e.selectFile(e.layout.Stem(owner)+".go", owner)
}

// sourceFile assembles imports for this native file only. Formatting precedes
// physical line mapping so diagnostics describe the actual source artifact.
func (e *emitter) sourceFile(name, pkg string) ([]byte, map[int]token.Position, error) {
	header := fmt.Sprintf("// Code generated by goalchemy. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	body := e.files[name].Bytes()
	f, err := parser.ParseFile(token.NewFileSet(), name, append([]byte(header), body...), 0)
	if err != nil {
		return append([]byte(header), body...), nil, fmt.Errorf("generated Go %s does not parse: %w", name, err)
	}
	used := map[string]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := s.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})
	var out bytes.Buffer
	out.WriteString(header)
	for _, imp := range []struct{ name, path string }{{"context", "context"}, {"io", "io"}, {"reflect", "reflect"}, {"rt", "goalchemyout/rt"}} {
		if used[imp.name] {
			fmt.Fprintf(&out, "import %q\n", imp.path)
		}
	}
	out.WriteString("\n")
	out.Write(body)
	src, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), nil, fmt.Errorf("generated Go %s does not parse: %w", name, err)
	}
	fset := token.NewFileSet()
	generatedPath := filepath.Join(e.outDir, name)
	f, err = parser.ParseFile(fset, generatedPath, src, parser.ParseComments)
	if err != nil {
		return src, nil, err
	}
	tf := fset.File(f.Pos())
	physicalLines := strings.Split(string(src), "\n")
	lines := map[int]token.Position{}
	for _, group := range f.Comments {
		for _, comment := range group.List {
			if !strings.HasPrefix(comment.Text, "/*line ") {
				continue
			}
			directive := strings.TrimSuffix(strings.TrimPrefix(comment.Text, "/*line "), "*/")
			split := strings.LastIndexByte(directive, ':')
			column, err := strconv.Atoi(directive[split+1:])
			if split < 0 || err != nil {
				return src, nil, fmt.Errorf("invalid generated line directive %q", comment.Text)
			}
			directive = directive[:split]
			split = strings.LastIndexByte(directive, ':')
			sourceLine, err := strconv.Atoi(directive[split+1:])
			if split < 0 || err != nil {
				return src, nil, fmt.Errorf("invalid generated line directive %q", comment.Text)
			}
			sourceName := directive[:split]
			if !filepath.IsAbs(sourceName) {
				sourceName = filepath.Join(filepath.Dir(generatedPath), sourceName)
			}
			end := tf.PositionFor(comment.End(), false)
			line := end.Line
			// Standalone directives describe the following declaration; inline
			// directives describe the statement following the comment on this line.
			if strings.TrimSpace(physicalLines[line-1][end.Column-1:]) == "" {
				line++
			}
			lines[line] = token.Position{Filename: sourceName, Line: sourceLine, Column: column}
		}
	}

	return src, lines, nil
}

func (e *emitter) use(contract string) {
	if contract != "" {
		e.contracts[contract] = true
	}
}

// opaqueContracts names a contract whose implementation declares each
// opaque handle type.
var opaqueContracts = map[string]string{
	"sync.Mutex":      "std.sync.mutex.lock",
	"sync.WaitGroup":  "std.sync.waitgroup.add",
	"context.Context": "std.context.background",
	"crypto.Key":      "lib.crypto.close",
	"http.Exchange":   "lib.http.exchange_close",
}

func (e *emitter) p_(format string, args ...any) {
	fmt.Fprintf(e.buf, format, args...)
}

func (e *emitter) sym(base string) string {
	s := base
	for i := 2; e.syms[s]; i++ {
		s = fmt.Sprintf("%s_%d", base, i)
	}
	e.syms[s] = true
	return s
}

func (e *emitter) nameTypes() {
	for _, f := range e.p.Funcs {
		e.syms[e.names.Symbol(f.Sym)] = true
	}
	for _, g := range e.p.Globals {
		e.syms[e.names.Symbol(g.Sym)] = true
	}
	for _, t := range e.p.Types.All {
		if t.Kind == ir.KNamed && t.Pkg != "" {
			e.typeNames[t] = e.sym(e.names.Type(t, "type_"))
		}
	}

	// Native exported methods keep their API names. Private method identities
	// include package paths, so assign collision-free names over the whole IR.
	identities := map[string]bool{}
	reserved := map[string]bool{}
	for _, t := range e.p.Types.All {
		for i, field := range t.U().Fields {
			reserved[field.Name] = true
			reserved[e.fieldName(t, i)] = true
		}
	}

	for _, f := range e.p.Funcs {
		if strings.Contains(f.MethodID, ".") {
			identities[f.MethodID] = true
		} else if f.MethodID != "" {
			reserved[methodShortName(f)] = true
		}
	}
	for _, t := range e.p.Types.All {
		for _, m := range t.Methods {
			if strings.Contains(m.ID, ".") {
				identities[m.ID] = true
			} else {
				reserved[m.Name] = true
			}
		}
		for _, m := range t.MethodSet {
			if strings.Contains(m.ID, ".") {
				identities[m.ID] = true
			} else {
				reserved[m.Name] = true
			}
		}
	}
	var ids []string
	for id := range identities {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	e.methodNames = map[string]string{}
	for i, id := range ids {
		n := fmt.Sprintf("method_%s_%d", naming.Identifier(id), i)
		if e.p.CompactNames {
			n = fmt.Sprintf("m_%d", i)
		}
		// One alias per identity must be safe on every native receiver type.
		for reserved[n] {
			n += "_"
		}
		reserved[n] = true
		e.methodNames[id] = n
	}
}

// methodName renders a method identity as a Go method name. Unexported
// methods keep package-qualified identity through a suffix.
func (e *emitter) methodName(id, name string) string {
	if n, ok := e.methodNames[id]; ok {
		return n
	}
	return name
}

func (e *emitter) fieldName(t *ir.Type, i int) string {
	f := t.U().Fields[i]
	if f.Embedded {
		ft := f.Type
		if ft.Kind == ir.KPointer {
			ft = ft.Elem
		}
		if n, ok := e.publicTypes[ft]; ok {
			return n
		}
		if n, ok := e.typeNames[ft]; ok {
			return n
		}
		return f.Name
	}
	if f.Name == "_" {
		return "_"
	}
	return f.Name
}

// typ renders an IR type as a Go type expression.
func (e *emitter) typ(t *ir.Type) string {
	if n, ok := e.publicTypes[t]; ok {
		return n
	}
	if n, ok := e.typeNames[t]; ok {
		return n
	}
	switch t.Kind {
	case ir.KBool, ir.KInt, ir.KString, ir.KFloat:
		return t.Basic
	case ir.KNamed:
		if t.Name == "error" {
			return "error"
		}
		return t.Name
	case ir.KSlice:
		return "[]" + e.typ(t.Elem)
	case ir.KArray:
		return fmt.Sprintf("[%d]%s", t.Len, e.typ(t.Elem))
	case ir.KPointer:
		return "*" + e.typ(t.Elem)
	case ir.KMap:
		return "rt.Map[" + e.typ(t.Key) + ", " + e.typ(t.Elem) + "]"
	case ir.KChan:
		return "rt.Chan[" + e.typ(t.Elem) + "]"
	case ir.KOpaque:
		e.use(opaqueContracts[t.Name])
		return "rt." + t.Obj
	case ir.KMapIter:
		m := t.Elem.U()
		return "*rt.MapIter[" + e.typ(m.Key) + ", " + e.typ(m.Elem) + "]"
	case ir.KStruct:
		var b strings.Builder
		b.WriteString("struct{")
		for i, f := range t.Fields {
			if i > 0 {
				b.WriteString("; ")
			}
			if f.Embedded {
				b.WriteString(e.typ(f.Type))
			} else {
				b.WriteString(e.fieldName(t, i) + " " + e.typ(f.Type))
			}
		}
		b.WriteString("}")
		return b.String()
	case ir.KInterface:
		if len(t.Methods) == 0 {
			return "any"
		}
		var b strings.Builder
		b.WriteString("interface{")
		for i, m := range t.Methods {
			if i > 0 {
				b.WriteString("; ")
			}
			// Interface methods use their method-identity convention. An
			// unrelated function value can share this signature and suspend.
			sig := e.syncType(m.Sig)
			if e.p.SuspMethods[m.ID] {
				sig = e.startType(m.Sig)
			}
			b.WriteString(e.methodName(m.ID, m.Name) + strings.TrimPrefix(sig, "func"))
		}
		b.WriteString("}")
		return b.String()
	case ir.KFunc:
		if e.susp(t) {
			return e.startType(t)
		}
		var b strings.Builder
		b.WriteString("func(")
		for i, p := range t.Params {
			if i > 0 {
				b.WriteString(", ")
			}
			if t.Variadic && i == len(t.Params)-1 {
				b.WriteString("..." + e.typ(p.Elem))
			} else {
				b.WriteString(e.typ(p))
			}
		}
		b.WriteString(")")
		if len(t.Results) == 1 {
			b.WriteString(" " + e.typ(t.Results[0]))
		} else if len(t.Results) > 1 {
			var rs []string
			for _, r := range t.Results {
				rs = append(rs, e.typ(r))
			}
			b.WriteString(" (" + strings.Join(rs, ", ") + ")")
		}
		return b.String()
	}
	panic(fmt.Sprintf("golang: cannot render type %s", t))
}

// susp reports whether values of function type t use the resumable
// calling convention: calling one returns a frame.
func (e *emitter) susp(t *ir.Type) bool { return e.p.SuspTypes[t.U()] }

// startType renders the resumable form of a function type. Under the
// native pause model it is an ordinary function taking the current task.
func (e *emitter) startType(t *ir.Type) string {
	if e.native() {
		s := "func(" + strings.Join(append([]string{"*rt.Task"}, e.paramTypes(t)...), ", ") + ")"
		if r := syncResults(e, t.U()); r != "" {
			s += " " + r
		}
		return s
	}
	return "func(" + strings.Join(e.paramTypes(t), ", ") + ") rt.Frame"
}

func (e *emitter) native() bool { return e.p.PauseModel == "native" }

// nativeBody renders a function body returning call's results, if any.
func nativeBody(n int, call string) string {
	if n == 0 {
		return call
	}
	return "return " + call
}

// syncType renders a function type in the ordinary convention.
func (e *emitter) syncType(t *ir.Type) string {
	t = t.U()
	s := "func(" + strings.Join(e.paramTypes(t), ", ") + ")"
	if r := syncResults(e, t); r != "" {
		s += " " + r
	}
	return s
}

func syncResults(e *emitter, t *ir.Type) string {
	switch len(t.Results) {
	case 0:
		return ""
	case 1:
		return e.typ(t.Results[0])
	}
	var rs []string
	for _, r := range t.Results {
		rs = append(rs, e.typ(r))
	}
	return "(" + strings.Join(rs, ", ") + ")"
}

func (e *emitter) paramTypes(t *ir.Type) []string {
	t = t.U()
	var ps []string
	for i, p := range t.Params {
		if t.Variadic && i == len(t.Params)-1 {
			ps = append(ps, "..."+e.typ(p.Elem))
		} else {
			ps = append(ps, e.typ(p))
		}
	}
	return ps
}

// forward renders parameters a0_.. for t and the matching call arguments.
func (e *emitter) forward(t *ir.Type) (params, args []string) {
	t = t.U()
	for i, pt := range e.paramTypes(t) {
		params = append(params, fmt.Sprintf("a%d_ %s", i, pt))
		a := fmt.Sprintf("a%d_", i)
		if t.Variadic && i == len(t.Params)-1 {
			a += "..."
		}
		args = append(args, a)
	}
	return params, args
}

// syncFrameBody renders the body of an rt.Sync closure calling call.
func syncFrameBody(n int, call string) string {
	if n == 0 {
		return call + "; return nil"
	}
	var rs []string
	for i := 0; i < n; i++ {
		rs = append(rs, fmt.Sprintf("r%d_", i))
	}
	return strings.Join(rs, ", ") + " := " + call + "; return []any{" + strings.Join(rs, ", ") + "}"
}

// adapt renders a function of t's resumable form wrapping the ordinary
// function value expr, which is evaluated once, now.
func (e *emitter) adapt(t *ir.Type, expr string) string {
	u := t.U()
	ps, as := e.forward(u)
	if e.native() {
		return fmt.Sprintf("func(f_ %s) %s { return func(%s) %s { %s } }(%s)",
			e.syncType(u), e.startType(u), strings.Join(append([]string{"_ *rt.Task"}, ps...), ", "), syncResults(e, u), nativeBody(len(u.Results), "f_("+strings.Join(as, ", ")+")"), expr)
	}
	body := syncFrameBody(len(u.Results), "f_("+strings.Join(as, ", ")+")")
	return fmt.Sprintf("func(f_ %s) %s { return func(%s) rt.Frame { return rt.Sync(func() []any { %s }) } }(%s)",
		e.syncType(u), e.startType(u), strings.Join(ps, ", "), body, expr)
}

// nativeMethod reports whether f is emitted as an ordinary Go method.
func (e *emitter) nativeMethod(f *ir.Func) bool {
	return isMethod(f) && !f.MaySuspend && !e.p.SuspMethods[f.MethodID]
}

func (e *emitter) typeDecls() {
	var named []*ir.Type
	for t := range e.typeNames {
		named = append(named, t)
	}
	sort.Slice(named, func(i, j int) bool { return e.typeNames[named[i]] < e.typeNames[named[j]] })
	for _, t := range named {
		if owner := e.layout.TypeOwner(t); owner != "" {
			e.selectPackage(owner)
		} else {
			e.selectFile("shared.go", "")
		}
		if named, ok := t.Go.(*types.Named); ok {
			e.p_("%s", e.lineDirective(named.Obj().Pos()))
		}
		e.p_("type %s %s\n\n", e.typeNames[t], e.typ(t.Underlying))
	}
	e.selectFile("shared.go", "")
	e.p_("func init() {\n")
	for _, t := range named {
		e.p_("\trt.RegisterType(reflect.TypeFor[%s](), %q)\n", e.typeNames[t], t.Name)
	}
	e.p_("}\n\n")
}

func (e *emitter) globals() {
	for _, g := range e.p.Globals {
		if g.Pkg != "" {
			e.selectPackage(g.Pkg)
		} else {
			e.selectFile("shared.go", "")
		}
		e.p_("%s", e.lineDirective(g.Pos))
		e.p_("var %s %s\n", e.names.Symbol(g.Sym), e.typ(g.Type))
	}
	e.p_("\n")
}

func (e *emitter) entry() {
	if e.p.Cooperative {
		e.use("core.task.spawn")
		start := e.names.Symbol(e.p.Entry.Sym) + "()"
		if e.native() && e.p.Entry.MaySuspend {
			start = "rt.NativeTask(func(t *rt.Task) []any { " + e.names.Symbol(e.p.Entry.Sym) + "(t); return nil })"
		} else if !e.p.Entry.MaySuspend {
			start = "rt.Sync(func() []any { " + e.names.Symbol(e.p.Entry.Sym) + "(); return nil })"
		}
		run := "RunMain"
		if ir.HostEntry(e.contracts) {
			run = "RunMainHost"
		}
		e.p_("func main() {\n\trt.%s(%s)\n}\n", run, start)
		return
	}
	e.p_("func main() {\n\trt.Main(func() {\n\t\t%s()\n", e.names.Symbol(e.p.Init.Sym))
	if e.p.Main != nil {
		e.p_("\t\t%s()\n", e.names.Symbol(e.p.Main.Sym))
	}
	e.p_("\t})\n}\n")
}

// isMethod reports whether f is emitted as a Go method.
func isMethod(f *ir.Func) bool { return f.MethodID != "" && !f.Wrapper && f.Recv != nil }

type fnEmitter struct {
	e     *emitter
	f     *ir.Func
	names map[*ir.Local]string
	used  map[string]bool
	b     *bytes.Buffer
	// frame is set when f is emitted as a resumable frame; locals are
	// fields of fr.
	frame bool
	// task is set when f is a native-pause function taking the task t.
	task bool
	// funcOf records the function a local holds when it was set by
	// MakeClosure or MakeBound, for recover identity of deferred calls.
	funcOf map[*ir.Local]*ir.Func
	folds  *structure.Folds
}

func (e *emitter) localNames(f *ir.Func) *fnEmitter {
	fe := &fnEmitter{e: e, f: f, names: map[*ir.Local]string{}, used: map[string]bool{}}
	for _, l := range f.Locals {
		fe.names[l] = e.names.Local(l, "_")
	}
	return fe
}

func (fe *fnEmitter) w(format string, args ...any) { fmt.Fprintf(fe.b, format, args...) }

func (fe *fnEmitter) name(l *ir.Local) string {
	if n, ok := fe.folds.Name(l); ok {
		return n
	}
	return fe.names[l]
}

func (fe *fnEmitter) local(l *ir.Local) string {
	if fe.frame {
		return "fr." + fe.name(l)
	}
	return fe.name(l)
}

// val renders an operand's current value.
func (fe *fnEmitter) val(v ir.Value) string {
	switch v := v.(type) {
	case *ir.Local:
		if s, ok := fe.folds.Use(v); ok {
			return s
		}
		if v.Boxed {
			return "(*" + fe.local(v) + ")"
		}
		return fe.local(v)
	case *ir.Const:
		return fe.e.constant(v)
	case *ir.FuncRef:
		ref := fe.e.funcRef(v.Func)
		if fe.e.susp(v.Type) && !v.Func.MaySuspend {
			return fe.e.adapt(v.Type, ref)
		}
		return ref
	}
	panic(fmt.Sprintf("golang: operand %T", v))
}

func (e *emitter) funcRef(f *ir.Func) string {
	if e.nativeMethod(f) {
		return "(" + e.typ(f.RecvType) + ")." + e.methodName(f.MethodID, methodShortName(f))
	}
	return e.names.Symbol(f.Sym)
}

func methodShortName(f *ir.Func) string {
	n := f.Name
	return n[strings.LastIndex(n, ".")+1:]
}

func (e *emitter) constant(c *ir.Const) string {
	t := e.typ(c.Type)
	if c.Nil {
		if nilWrapper(c.Type) {
			return "(" + t + "{})"
		}
		return "(" + t + ")(nil)"
	}
	if c.Type.U().Kind == ir.KFloat {
		return e.typ(c.Type) + "(" + ir.FloatLiteral(c) + ")"
	}
	switch c.Val.Kind() {
	case constant.Bool:
		if c.Type.Kind == ir.KNamed {
			return t + "(" + c.Val.ExactString() + ")"
		}
		return c.Val.ExactString()
	case constant.String:
		s := strconv.Quote(constant.StringVal(c.Val))
		if c.Type.Kind == ir.KNamed {
			return t + "(" + s + ")"
		}
		return s
	case constant.Int:
		return t + "(" + c.Val.ExactString() + ")"
	}
	panic("golang: unsupported constant " + c.Val.String())
}

// nilWrapper identifies source nil values represented by comparable Go
// handles rather than native nil. U also handles named source aliases.
func nilWrapper(t *ir.Type) bool {
	u := t.U()
	return u.Kind == ir.KMap || u.Kind == ir.KChan || (u.Kind == ir.KOpaque && u.Name == "context.Context")
}

func (fe *fnEmitter) place(p *ir.Place) string {
	var s string
	switch r := p.Root.(type) {
	case ir.LocalRoot:
		s = fe.val(r.Local)
	case ir.GlobalRoot:
		s = fe.e.names.Symbol(r.Global.Sym)
	case ir.DerefRoot:
		s = "(*" + fe.val(r.Ptr) + ")"
	case ir.SliceRoot:
		s = fe.val(r.Slice) + "[" + fe.val(r.Index) + "]"
	case ir.ValueRoot:
		s = fe.val(r.Value)
	}
	cur := placeRootType(p)
	for _, pr := range p.Path {
		if pr.Index != nil {
			s += "[" + fe.val(pr.Index) + "]"
		} else {
			s += "." + fe.e.fieldName(cur, pr.Field)
		}
		cur = pr.Type
	}
	return s
}

func placeRootType(p *ir.Place) *ir.Type {
	switch r := p.Root.(type) {
	case ir.LocalRoot:
		return r.Local.Type
	case ir.GlobalRoot:
		return r.Global.Type
	case ir.DerefRoot:
		return r.Ptr.IRType().U().Elem
	case ir.SliceRoot:
		return r.Slice.IRType().U().Elem
	case ir.ValueRoot:
		return r.Value.IRType()
	}
	return nil
}

func (e *emitter) signature(f *ir.Func, fe *fnEmitter, skipRecv bool) string {
	var ps []string
	if fe.task {
		ps = append(ps, "t *rt.Task")
		for _, l := range f.Env {
			ps = append(ps, fe.local(l)+" *"+e.typ(l.Type))
		}
	}
	for i, p := range f.Params {
		if skipRecv && i == 0 {
			continue
		}
		name := fe.local(p)
		if p.Boxed {
			name = "p_" + name
		}
		t := e.typ(p.Type)
		if f.Sig.Variadic && i == len(f.Params)-1 {
			t = "..." + e.typ(p.Type.U().Elem)
		}
		ps = append(ps, name+" "+t)
	}
	s := "(" + strings.Join(ps, ", ") + ")"
	var rs []string
	for i, r := range f.Results {
		if hasDefer(f) {
			rs = append(rs, fmt.Sprintf("gres%d %s", i, e.typ(r.Type)))
		} else {
			rs = append(rs, e.typ(r.Type))
		}
	}
	if hasDefer(f) && len(rs) == 1 {
		return s + " (" + rs[0] + ")"
	}
	switch len(rs) {
	case 0:
	case 1:
		s += " " + rs[0]
	default:
		s += " (" + strings.Join(rs, ", ") + ")"
	}
	return s
}

func (e *emitter) function(f *ir.Func) {
	e.p_("%s", e.lineDirective(f.Pos))
	if f.MaySuspend && !e.native() {
		e.frameFunction(f)
		return
	}
	fe := e.localNames(f)
	fe.task = f.MaySuspend
	var body bytes.Buffer
	fe.b = &body
	fe.body()
	if isMethod(f) && !e.nativeMethod(f) {
		e.p_("func %s%s {\n", e.names.Symbol(f.Sym), e.signature(f, fe, false))
		e.buf.Write(body.Bytes())
		e.p_("}\n\n")
		e.startMethod(f, f.MaySuspend)
		return
	}
	if isMethod(f) {
		r := f.Params[0]
		rn := fe.local(r)
		if r.Boxed {
			rn = "p_" + rn
		}
		e.p_("func (%s %s) %s%s {\n", rn, e.typ(r.Type), e.methodName(f.MethodID, methodShortName(f)), e.signature(f, fe, true))
	} else {
		e.p_("func %s%s {\n", e.names.Symbol(f.Sym), e.signature(f, fe, false))
	}
	e.buf.Write(body.Bytes())
	e.p_("}\n\n")
}

// startMethod emits the resumable Go method for a declared method whose
// identity uses the resumable convention; it delegates to the function sym.
func (e *emitter) startMethod(f *ir.Func, isFrame bool) {
	m := e.typ(&ir.Type{Kind: ir.KFunc, Params: f.Sig.Params[1:], Results: f.Sig.Results, Variadic: f.Sig.Variadic})
	_ = m
	r := f.Params[0]
	var ps, as []string
	for i, p := range f.Params[1:] {
		t := e.typ(p.Type)
		a := fmt.Sprintf("a%d_", i)
		if f.Sig.Variadic && i == len(f.Params)-2 {
			t = "..." + e.typ(p.Type.U().Elem)
			a += "..."
		}
		ps = append(ps, fmt.Sprintf("a%d_ %s", i, t))
		as = append(as, a)
	}
	if e.native() {
		recv := []string{"r_"}
		if isFrame {
			recv = []string{"t", "r_"}
		}
		call := e.names.Symbol(f.Sym) + "(" + strings.Join(append(recv, as...), ", ") + ")"
		res := syncResults(e, f.Sig.U())
		if res != "" {
			res = " " + res
		}
		e.p_("func (r_ %s) %s(%s)%s {\n%s\n}\n\n", e.typ(r.Type), e.methodName(f.MethodID, methodShortName(f)), strings.Join(append([]string{"t *rt.Task"}, ps...), ", "), res, nativeBody(len(f.Results), call))
		return
	}
	call := e.names.Symbol(f.Sym) + "(" + strings.Join(append([]string{"r_"}, as...), ", ") + ")"
	body := "return " + call
	if !isFrame {
		body = "return rt.Sync(func() []any { " + syncFrameBody(len(f.Results), call) + " })"
	}
	e.p_("func (r_ %s) %s(%s) rt.Frame {\n%s\n}\n\n", e.typ(r.Type), e.methodName(f.MethodID, methodShortName(f)), strings.Join(ps, ", "), body)
}

// frameFunction emits a suspending function as a resumable frame: a struct
// holding its locals and resume point, a starter that binds the arguments,
// and a Step method running the blocks until return or a pause point.
func (e *emitter) frameFunction(f *ir.Func) {
	fe := e.localNames(f)
	fe.frame = true
	fe.analyze()
	fe.frame = false
	ft := "frame_" + e.names.Symbol(f.Sym)
	e.p_("type %s struct {\n\trt.FrameBase\n", ft)
	for _, l := range f.Locals {
		if fe.folds.Temp(l) {
			continue
		}
		t := e.typ(l.Type)
		if l.Boxed {
			t = "*" + t
		}
		e.p_("\t%s %s\n", fe.names[l], t)
	}
	e.p_("}\n\n")
	var ps []string
	inputs := append(append([]*ir.Local(nil), f.Env...), f.Params...)
	for i, l := range inputs {
		t := e.typ(l.Type)
		if l.Kind == ir.LEnv {
			t = "*" + t
		}
		if f.Sig.Variadic && i == len(inputs)-1 && len(f.Params) > 0 {
			t = "..." + e.typ(l.Type.U().Elem)
		}
		ps = append(ps, fe.names[l]+" "+t)
	}
	e.p_("func %s(%s) rt.Frame {\n\tfr := &%s{}\n", e.names.Symbol(f.Sym), strings.Join(ps, ", "), ft)
	for _, l := range inputs {
		if l.Boxed && l.Kind != ir.LEnv {
			e.p_("\tfr.%s = &%s\n", fe.names[l], fe.names[l])
		} else {
			e.p_("\tfr.%s = %s\n", fe.names[l], fe.names[l])
		}
	}
	e.p_("\treturn fr\n}\n\n")
	fe.frame = true
	var rs []string
	for _, r := range f.Results {
		rs = append(rs, fe.val(r))
	}
	e.p_("func (fr *%s) Results() []any { return []any{%s} }\n\n", ft, strings.Join(rs, ", "))
	var body bytes.Buffer
	fe.b = &body
	fe.frameBody()
	e.p_("func (fr *%s) Step(t *rt.Task) {\n", ft)
	e.buf.Write(body.Bytes())
	e.p_("}\n\n")
	if isMethod(f) {
		e.startMethod(f, true)
	}
}

func (fe *fnEmitter) scanFuncs() {
	fe.funcOf = map[*ir.Local]*ir.Func{}
	for _, b := range fe.f.Blocks {
		for _, in := range b.Instrs {
			switch i := in.(type) {
			case *ir.MakeClosure:
				fe.funcOf[i.Dst] = i.Func
			case *ir.MakeBound:
				fe.funcOf[i.Dst] = i.Func
			}
		}
	}
}

func (fe *fnEmitter) frameBody() {
	fe.scanFuncs()
	fe.structured()
}

// resume assigns a paused operation's results from the task.
func (fe *fnEmitter) resume(op ir.Instr) {
	e := fe.e
	switch i := op.(type) {
	case *ir.Call:
		for k, d := range i.Dsts {
			if d != nil {
				fe.w("%s = rt.As[%s](t.RV[%d])\n", fe.val(d), e.typ(d.Type), k)
			}
		}
	case *ir.Recv:
		if i.Dst != nil {
			fe.w("%s = rt.As[%s](t.RV[0])\n", fe.val(i.Dst), e.typ(i.Dst.Type))
		}
		if i.Ok != nil {
			fe.w("%s = t.RV[1].(bool)\n", fe.val(i.Ok))
		}
	case *ir.Select:
		fe.w("%s = t.RV[0].(int)\n", fe.val(i.Index))
		for k, c := range i.Cases {
			if c.Send || c.Dst == nil && c.Ok == nil {
				continue
			}
			fe.w("if t.RV[0].(int) == %d {\n", k)
			if c.Dst != nil {
				fe.w("%s = rt.As[%s](t.RV[1])\n", fe.val(c.Dst), e.typ(c.Dst.Type))
			}
			if c.Ok != nil {
				fe.w("%s = t.RV[2].(bool)\n", fe.val(c.Ok))
			}
			fe.w("}\n")
		}
	}
}

// pause emits a pause point: record the resume block, start the
// operation, and return to the trampoline.
func (fe *fnEmitter) pause(p *ir.Pause) {
	e := fe.e
	if fe.task {
		fe.nativePause(p)
		return
	}
	fe.w("fr.PC = %d\n", p.Next.ID)
	switch i := p.Op.(type) {
	case *ir.Call:
		if i.Kind == ir.CallExtern {
			e.use(i.Extern.Contract)
			as := []string{"t"}
			for _, a := range i.Args {
				as = append(as, fe.externArg(a))
			}
			fe.w("%s(%s)\n", e.externSym(i.Extern.Contract), strings.Join(as, ", "))
		} else {
			fe.w("rt.Call(t, %s)\n", fe.callExpr(i))
		}
	case *ir.Send:
		e.use("core.chan.send")
		fe.w("%s.Send(t, %s)\n", fe.chanVal(i.Ch), fe.val(i.V))
	case *ir.Recv:
		e.use("core.chan.recv")
		fe.w("%s.Recv(t)\n", fe.chanVal(i.Ch))
	case *ir.Select:
		e.use("core.select")
		var cs []string
		for _, c := range i.Cases {
			if c.Send {
				cs = append(cs, fmt.Sprintf("rt.Case(%s, true, %s)", fe.chanVal(c.Ch), fe.val(c.V)))
			} else {
				cs = append(cs, fmt.Sprintf("rt.RecvCase(%s)", fe.chanVal(c.Ch)))
			}
		}
		fe.w("rt.Select(t, []rt.SelectCase{%s}, %v)\n", strings.Join(cs, ", "), i.Default)
	default:
		panic(fmt.Sprintf("golang: pause on %T", p.Op))
	}
	fe.w("return\n")
}

// nativePause emits a pause point as a blocking operation: generated callees
// return their results directly; runtime primitives leave them in t.RV
// after rt.Wait hands the turn back to the scheduler while the task blocks.
func (fe *fnEmitter) nativePause(p *ir.Pause) {
	e := fe.e
	switch i := p.Op.(type) {
	case *ir.Call:
		if i.Kind == ir.CallExtern {
			e.use(i.Extern.Contract)
			as := []string{"t"}
			for _, a := range i.Args {
				as = append(as, fe.externArg(a))
			}
			fe.w("%s(%s)\nrt.Wait(t)\n", e.externSym(i.Extern.Contract), strings.Join(as, ", "))
			fe.resume(i)
			break
		}
		var ds []string
		for _, d := range i.Dsts {
			ds = append(ds, fe.assignDst(d))
		}
		call := fe.taskCallExpr(i)
		if len(ds) > 0 {
			fe.w("%s = %s\n", strings.Join(ds, ", "), call)
		} else {
			fe.w("%s\n", call)
		}
	case *ir.Send:
		e.use("core.chan.send")
		fe.w("%s.Send(t, %s)\nrt.Wait(t)\n", fe.chanVal(i.Ch), fe.val(i.V))
	case *ir.Recv:
		e.use("core.chan.recv")
		fe.w("%s.Recv(t)\nrt.Wait(t)\n", fe.chanVal(i.Ch))
		fe.resume(i)
	case *ir.Select:
		e.use("core.select")
		var cs []string
		for _, c := range i.Cases {
			if c.Send {
				cs = append(cs, fmt.Sprintf("rt.Case(%s, true, %s)", fe.chanVal(c.Ch), fe.val(c.V)))
			} else {
				cs = append(cs, fmt.Sprintf("rt.RecvCase(%s)", fe.chanVal(c.Ch)))
			}
		}
		fe.w("rt.Select(t, []rt.SelectCase{%s}, %v)\nrt.Wait(t)\n", strings.Join(cs, ", "), i.Default)
		fe.resume(i)
	default:
		panic(fmt.Sprintf("golang: pause on %T", p.Op))
	}
}

// taskCallExpr renders a call using the native-pause convention: the
// current task is the first argument of a suspending callee.
func (fe *fnEmitter) taskCallExpr(c *ir.Call) string {
	switch c.Kind {
	case ir.CallStatic:
		if c.Func.MaySuspend {
			return fe.e.names.Symbol(c.Func.Sym) + "(" + strings.Join(append([]string{"t"}, fe.argList(c, c.Func.Sig, 0)...), ", ") + ")"
		}
	case ir.CallValue:
		if fe.e.susp(c.Fn.IRType()) {
			return fe.val(c.Fn) + "(" + strings.Join(append([]string{"t"}, fe.argList(c, c.Fn.IRType().U(), 0)...), ", ") + ")"
		}
	case ir.CallInterface:
		if fe.e.p.SuspMethods[c.Method] {
			it := c.Recv.IRType().U()
			var sig *ir.Type
			name := c.Method
			for _, m := range it.Methods {
				if m.ID == c.Method {
					sig, name = m.Sig, m.Name
				}
			}
			return fe.val(c.Recv) + "." + fe.e.methodName(c.Method, name) + "(" + strings.Join(append([]string{"t"}, fe.argList(c, sig, 0)...), ", ") + ")"
		}
	}
	return fe.callExpr(c)
}

// externAdapts emits a capability call whose function-typed results must be
// adapted to the resumable convention, reporting whether it did.
func (fe *fnEmitter) externAdapts(c *ir.Call) bool {
	need := false
	for _, d := range c.Dsts {
		if d != nil && d.Type.U().Kind == ir.KFunc && fe.e.susp(d.Type) {
			need = true
		}
	}
	if !need {
		return false
	}
	var tmps []string
	for k := range c.Dsts {
		tmps = append(tmps, fmt.Sprintf("x%d_", k))
	}
	fe.w("{\n%s := %s\n", strings.Join(tmps, ", "), fe.callExpr(c))
	for k, d := range c.Dsts {
		if d == nil {
			continue
		}
		v := tmps[k]
		if d.Type.U().Kind == ir.KFunc && fe.e.susp(d.Type) {
			v = fe.e.adapt(d.Type, v)
		}
		fe.w("%s = %s\n", fe.val(d), v)
	}
	fe.w("}\n")
	return true
}

func (fe *fnEmitter) externArg(a ir.Value) string {
	v := fe.val(a)
	if t := a.IRType(); t.Kind == ir.KNamed && t.U().Kind == ir.KInt {
		v = t.U().Basic + "(" + v + ")"
	}
	return v
}

// body writes local declarations and the structured body.
func (fe *fnEmitter) body() {
	f := fe.f
	fe.scanFuncs()
	fe.analyze()
	params := map[*ir.Local]bool{}
	for _, p := range f.Params {
		params[p] = true
	}
	for _, l := range f.Env {
		params[l] = true
	}
	for _, l := range f.Locals {
		if params[l] && !l.Boxed || fe.folds.Temp(l) {
			continue
		}
		if params[l] && l.Boxed && containsLocal(f.Env, l) {
			continue
		}
		t := fe.e.typ(l.Type)
		if l.Boxed {
			t = "*" + t
		}
		fe.w("var %s %s\n_ = %s\n", fe.local(l), t, fe.local(l))
	}
	for _, p := range f.Params {
		if p.Boxed {
			fe.w("%s = &p_%s\n", fe.local(p), fe.local(p))
		}
	}
	if hasDefer(f) && len(f.Results) > 0 {
		// Runs after every source defer, so results reflect deferred writes.
		fe.w("defer func() {\n")
		for i, r := range f.Results {
			fe.w("gres%d = %s\n", i, fe.val(r))
		}
		fe.w("}()\n")
	}
	fe.structured()
}

// analyze decides which temporaries fold into the expressions using them.
func (fe *fnEmitter) analyze() {
	structure.Analyze(fe.f, structure.FoldOptions{Inline: fe.inline(), Order: structure.CallsInOrder}, goProbe{fe}, func(fs *structure.Folds) { fe.folds = fs })
}

func (fe *fnEmitter) inline() bool { return !fe.frame }

var goSyntax = structure.Syntax{
	Indent: "\t", If: "if %s {", ElseIf: "} else if %s {", Else: "} else {", End: "}",
	Loop: "for {", While: "for %s {", LoopLabel: "%s:\n", LabelName: "L%d",
	Break: "break", BreakTo: "break %s", Continue: "continue", ContinueTo: "continue %s",
	Goto: "goto %s", Label: "%s:", Not: "!%s", And: "%s && %s", Or: "%s || %s",
	EntryLabel: "b%d:", GotoEntry: "goto b%d",
}

// structured writes the function's control flow as structured statements;
// resumable frames start with a switch to the block their task resumes at.
func (fe *fnEmitter) structured() {
	inline := fe.inline()
	body := structure.Build(fe.f, structure.Options{Inline: inline, Empty: func(b *ir.Block) bool { return fe.folds.Empty(b, inline) }})
	syn := goSyntax
	syn.Resume = func(heads []*ir.Block) string {
		var b strings.Builder
		b.WriteString("switch fr.PC {\n")
		for _, h := range heads {
			fmt.Fprintf(&b, "case %d:\ngoto b%d\n", h.ID, h.ID)
		}
		b.WriteString("}")
		return b.String()
	}
	fe.w("%s", structure.Resolve(structure.Print(body, syn, goEmitter{fe}, 0)))
}

func (fe *fnEmitter) capture(fn func()) string {
	saved := fe.b
	var b bytes.Buffer
	fe.b = &b
	fn()
	fe.b = saved
	return b.String()
}

// goEmitter prints the target-specific statements of a structured body.
type goEmitter struct{ fe *fnEmitter }

func (g goEmitter) Code(b *ir.Block) string {
	fe := g.fe
	return fe.capture(func() {
		if b.ResumeOf != nil && fe.frame {
			fe.resume(b.ResumeOf)
		}
		for _, in := range b.Instrs {
			if fe.folds.Folded(in) {
				continue
			}
			fe.line(in.Position())
			fe.instr(in)
		}
	})
}

func (g goEmitter) Leaf(b *ir.Block, t ir.Terminator) string {
	return g.fe.capture(func() {
		g.fe.line(t.Position())
		g.fe.term(t)
	})
}

func (g goEmitter) Pause(p *ir.Pause) string {
	if g.fe.folds.FoldedPause(p) {
		return ""
	}
	return g.fe.capture(func() {
		g.fe.line(p.Position())
		g.fe.nativePause(p)
	})
}

func (g goEmitter) Cond(v ir.Value) string    { return g.fe.val(v) }
func (g goEmitter) Mark(pos token.Pos) string { return g.fe.e.lineDirective(pos) }

// goProbe renders statements for fold analysis.
type goProbe struct{ fe *fnEmitter }

func (g goProbe) Instr(in ir.Instr) string { return g.fe.capture(func() { g.fe.instr(in) }) }
func (g goProbe) Pause(p *ir.Pause) string { return g.fe.capture(func() { g.fe.nativePause(p) }) }
func (g goProbe) Cond(v ir.Value) string   { return g.fe.val(v) }
func (g goProbe) Assign(l *ir.Local) (string, string) {
	return g.fe.val(l) + " = ", ""
}
func (g goProbe) Leaf(b *ir.Block, t ir.Terminator) string {
	return g.fe.capture(func() { g.fe.term(t) })
}

// line emits a line directive so compiler and runtime positions refer to
// the Goalchemy source.
func (fe *fnEmitter) line(pos token.Pos) {
	fe.w("%s", fe.e.lineDirective(pos))
}

func (e *emitter) lineDirective(pos token.Pos) string {
	if !pos.IsValid() || e.p.Fset == nil || e.p.NoLineDirectives {
		return ""
	}
	p := e.p.Fset.Position(pos)
	name := p.Filename
	if rel, err := filepath.Rel(e.outDir, name); err == nil && e.outDir != "" {
		name = filepath.ToSlash(rel)
	}
	return fmt.Sprintf("/*line %s:%d:%d*/", name, p.Line, p.Column)
}

func containsLocal(ls []*ir.Local, l *ir.Local) bool {
	for _, x := range ls {
		if x == l {
			return true
		}
	}
	return false
}

func (fe *fnEmitter) assignDst(l *ir.Local) string {
	if l == nil {
		return "_"
	}
	return fe.val(l)
}

func (fe *fnEmitter) args(c *ir.Call, sig *ir.Type, skip int) string {
	return strings.Join(fe.argList(c, sig, skip), ", ")
}

func (fe *fnEmitter) argList(c *ir.Call, sig *ir.Type, skip int) []string {
	var as []string
	for i, a := range c.Args {
		s := fe.val(a)
		if sig != nil && sig.Variadic && i == len(c.Args)-1 {
			s += "..."
		}
		as = append(as, s)
	}
	return as[skip:]
}

func (fe *fnEmitter) callExpr(c *ir.Call) string {
	switch c.Kind {
	case ir.CallStatic:
		f := c.Func
		if fe.e.nativeMethod(f) {
			return fe.val(c.Args[0]) + "." + fe.e.methodName(f.MethodID, methodShortName(f)) + "(" + fe.args(c, f.Sig, 1) + ")"
		}
		return fe.e.names.Symbol(f.Sym) + "(" + fe.args(c, f.Sig, 0) + ")"
	case ir.CallValue:
		return fe.val(c.Fn) + "(" + fe.args(c, c.Fn.IRType().U(), 0) + ")"
	case ir.CallInterface:
		it := c.Recv.IRType().U()
		var sig *ir.Type
		name := c.Method
		for _, m := range it.Methods {
			if m.ID == c.Method {
				sig, name = m.Sig, m.Name
			}
		}
		return fe.val(c.Recv) + "." + fe.e.methodName(c.Method, name) + "(" + fe.args(c, sig, 0) + ")"
	case ir.CallExtern:
		fe.e.use(c.Extern.Contract)
		var as []string
		for _, a := range c.Args {
			as = append(as, fe.externArg(a))
		}
		return fe.e.externSym(c.Extern.Contract) + "(" + strings.Join(as, ", ") + ")"
	}
	panic("golang: call kind")
}

// externSym returns the target symbol mapped to a capability contract.
func (e *emitter) externSym(contract string) string {
	if s, ok := e.symbols[contract]; ok {
		return s
	}
	return "rt." + externSymbol(contract)
}

func externSymbol(contract string) string {
	parts := strings.Split(contract, ".")
	var b strings.Builder
	for _, p := range parts {
		for _, w := range strings.Split(p, "_") {
			if w != "" {
				b.WriteString(strings.ToUpper(w[:1]) + w[1:])
			}
		}
	}
	return b.String()
}

func (fe *fnEmitter) instr(in ir.Instr) {
	e := fe.e
	switch i := in.(type) {
	case *ir.DeclVar:
		if i.L.Boxed {
			fe.w("%s = new(%s)\n", fe.local(i.L), e.typ(i.L.Type))
			if i.Init != nil {
				fe.w("*%s = %s\n", fe.local(i.L), fe.val(i.Init))
			}
			return
		}
		if i.Init != nil {
			fe.w("%s = %s\n", fe.local(i.L), fe.val(i.Init))
		} else {
			fe.w("%s = *new(%s)\n", fe.local(i.L), e.typ(i.L.Type))
		}
	case *ir.Assign:
		fe.w("%s = %s\n", fe.val(i.Dst), fe.val(i.Src))
	case *ir.Zero:
		fe.w("%s = *new(%s)\n", fe.val(i.Dst), e.typ(i.Dst.Type))
	case *ir.Load:
		fe.w("%s = %s\n", fe.val(i.Dst), fe.place(i.Place))
	case *ir.Store:
		fe.w("%s = %s\n", fe.place(i.Place), fe.val(i.V))
	case *ir.AddrOf:
		if dr, ok := i.Place.Root.(ir.DerefRoot); ok && len(i.Place.Path) == 0 {
			fe.w("%s = %s\n", fe.val(i.Dst), fe.val(dr.Ptr))
			return
		}
		if lr, ok := i.Place.Root.(ir.LocalRoot); ok && len(i.Place.Path) == 0 && lr.Local.Boxed {
			fe.w("%s = %s\n", fe.val(i.Dst), fe.local(lr.Local))
			return
		}
		fe.w("%s = &%s\n", fe.val(i.Dst), fe.place(i.Place))
	case *ir.New:
		fe.w("%s = new(%s)\n", fe.val(i.Dst), e.typ(i.Dst.Type.U().Elem))
	case *ir.UnOp:
		if x, ok := i.X.(*ir.Local); ok && i.Op == ir.Not {
			if d, ok := fe.folds.Def(x); ok {
				if b, ok := d.(*ir.BinOp); ok && (b.Op == ir.Eq || b.Op == ir.Ne) {
					fe.w("%s = %s\n", fe.val(i.Dst), fe.binExpr(b, map[ir.BinOpKind]ir.BinOpKind{ir.Eq: ir.Ne, ir.Ne: ir.Eq}[b.Op]))
					return
				}
			}
		}
		op := map[ir.UnOpKind]string{ir.Neg: "-", ir.Not: "!", ir.BitNot: "^"}[i.Op]
		fe.w("%s = %s%s\n", fe.val(i.Dst), op, fe.val(i.X))
	case *ir.BinOp:
		switch i.Op {
		case ir.Min, ir.Max:
			fe.w("%s = %s(%s, %s)\n", fe.val(i.Dst), i.Op, fe.val(i.X), fe.val(i.Y))
		default:
			if i.Dst.Type.U().Kind == ir.KFloat {
				fe.w("%s = %s(%s %s %s)\n", fe.val(i.Dst), e.typ(i.Dst.Type), fe.val(i.X), i.Op, fe.val(i.Y))
				break
			}
			fe.w("%s = %s\n", fe.val(i.Dst), fe.binExpr(i, i.Op))
		}
	case *ir.Convert:
		switch i.Kind {
		case ir.ConvStringToBytes:
			e.use("core.string.to_bytes")
			fe.w("%s = %s(rt.StringToBytes(string(%s)))\n", fe.val(i.Dst), parenType(e.typ(i.Dst.Type)), fe.val(i.X))
			return
		case ir.ConvStringToRunes:
			e.use("core.string.to_runes")
			fe.w("%s = %s(rt.StringToRunes(string(%s)))\n", fe.val(i.Dst), parenType(e.typ(i.Dst.Type)), fe.val(i.X))
			return
		}
		fe.w("%s = %s(%s)\n", fe.val(i.Dst), parenType(e.typ(i.Dst.Type)), fe.val(i.X))
	case *ir.MakeInterface:
		fe.w("%s = %s(%s)\n", fe.val(i.Dst), parenType(e.typ(i.Dst.Type)), fe.val(i.X))
	case *ir.TypeAssert:
		ok := "ok_"
		if i.Ok != nil {
			fe.w("%s, %s = %s.(%s)\n", fe.val(i.Dst), fe.val(i.Ok), fe.val(i.X), e.typ(i.T))
			return
		}
		fe.w("{\nvar %s bool\n%s, %s = %s.(%s)\n", ok, fe.val(i.Dst), ok, fe.val(i.X), e.typ(i.T))
		args := []string{fe.val(i.X), strconv.Quote(ir.TypeString(i.X.IRType())), strconv.Quote(ir.TypeString(i.T))}
		if i.T.IsInterface() {
			args = append(args, "(*"+e.typ(i.T)+")(nil)")
			for _, m := range i.T.U().Methods {
				args = append(args, strconv.Quote(e.methodName(m.ID, m.Name)), strconv.Quote(m.Name))
			}
		} else {
			args = append(args, "nil")
		}
		fe.w("if !%s {\nrt.PanicAssert(%s)\n}\n}\n", ok, strings.Join(args, ", "))
	case *ir.Call:
		if i.Kind == ir.CallExtern && fe.externAdapts(i) {
			return
		}
		var ds []string
		for _, d := range i.Dsts {
			ds = append(ds, fe.assignDst(d))
		}
		if len(ds) > 0 {
			fe.w("%s = %s\n", strings.Join(ds, ", "), fe.callExpr(i))
		} else {
			fe.w("%s\n", fe.callExpr(i))
		}
	case *ir.MakeClosure:
		fe.closure(i)
	case *ir.MakeBound:
		fe.makeBound(i)
	case *ir.MakeIfaceBound:
		name := i.Method
		for _, m := range i.Recv.IRType().U().Methods {
			if m.ID == i.Method {
				name = m.Name
			}
		}
		v := fe.val(i.Recv) + "." + e.methodName(i.Method, name)
		if e.susp(i.Dst.Type) && !e.p.SuspMethods[i.Method] {
			v = e.adapt(i.Dst.Type, v)
		}
		fe.w("%s = %s\n", fe.val(i.Dst), v)
	case *ir.Len:
		if i.X.IRType().U().Kind == ir.KChan {
			e.use("core.chan.len")
			fe.w("%s = %s.Len()\n", fe.val(i.Dst), fe.chanVal(i.X))
			return
		}
		if i.X.IRType().U().Kind == ir.KMap {
			e.use("core.map.len")
			fe.w("%s = %s.Len()\n", fe.val(i.Dst), fe.mapVal(i.X))
			return
		}
		fe.w("%s = len(%s)\n", fe.val(i.Dst), fe.val(i.X))
	case *ir.Cap:
		if i.X.IRType().U().Kind == ir.KChan {
			e.use("core.chan.cap")
			fe.w("%s = %s.Cap()\n", fe.val(i.Dst), fe.chanVal(i.X))
			return
		}
		fe.w("%s = cap(%s)\n", fe.val(i.Dst), fe.val(i.X))
	case *ir.MakeSlice:
		fe.w("%s = make(%s, %s, %s)\n", fe.val(i.Dst), e.typ(i.Dst.Type), fe.val(i.Len), fe.val(i.Cap))
	case *ir.MakeMap:
		e.use("core.map.make")
		m := i.Dst.Type.U()
		if i.Dst.Type.Kind == ir.KNamed {
			fe.w("%s = %s(rt.NewMap[%s, %s]())\n", fe.val(i.Dst), e.typ(i.Dst.Type), e.typ(m.Key), e.typ(m.Elem))
		} else {
			fe.w("%s = rt.NewMap[%s, %s]()\n", fe.val(i.Dst), e.typ(m.Key), e.typ(m.Elem))
		}
	case *ir.Append:
		e.use("core.slice.append")
		switch {
		case i.Spread != nil && i.Spread.IRType().U().Kind == ir.KString:
			fe.w("%s = rt.AppendString(%s, %s)\n", fe.val(i.Dst), fe.val(i.S), fe.val(i.Spread))
		case i.Spread != nil:
			fe.w("%s = rt.Append(%s, %s...)\n", fe.val(i.Dst), fe.val(i.S), fe.val(i.Spread))
		default:
			var es []string
			for _, x := range i.Elems {
				es = append(es, fe.val(x))
			}
			fe.w("%s = rt.Append(%s)\n", fe.val(i.Dst), strings.Join(append([]string{fe.val(i.S)}, es...), ", "))
		}
	case *ir.Copy:
		fe.w("%s = copy(%s, %s)\n", fe.val(i.N), fe.val(i.Dst), fe.val(i.Src))
	case *ir.IndexString:
		fe.w("%s = %s[%s]\n", fe.val(i.Dst), fe.val(i.S), fe.val(i.I))
	case *ir.SliceOp:
		lo, hi, mx := "", "", ""
		if i.Lo != nil {
			lo = fe.val(i.Lo)
		}
		if i.Hi != nil {
			hi = fe.val(i.Hi)
		}
		x := fe.val(i.X)
		if i.Max != nil {
			mx = fe.val(i.Max)
			fe.w("%s = %s[%s:%s:%s]\n", fe.val(i.Dst), x, lo, hi, mx)
		} else {
			fe.w("%s = %s[%s:%s]\n", fe.val(i.Dst), x, lo, hi)
		}
	case *ir.MapLookup:
		e.use("core.map.lookup")
		fe.w("%s, %s = %s.Get(%s)\n", fe.val(i.Dst), fe.assignDst(i.Ok), fe.mapVal(i.M), fe.val(i.K))
	case *ir.MapStore:
		e.use("core.map.store")
		fe.w("%s.Set(%s, %s)\n", fe.mapVal(i.M), fe.val(i.K), fe.val(i.V))
	case *ir.MapDelete:
		e.use("core.map.delete")
		fe.w("%s.Delete(%s)\n", fe.mapVal(i.M), fe.val(i.K))
	case *ir.Clear:
		if i.X.IRType().U().Kind == ir.KMap {
			e.use("core.map.clear")
			fe.w("%s.Clear()\n", fe.mapVal(i.X))
		} else {
			fe.w("clear(%s)\n", fe.val(i.X))
		}
	case *ir.DecodeRune:
		e.use("core.string.decode_rune")
		fe.w("%s, %s = rt.DecodeRune(%s, %s)\n", fe.val(i.Rune), fe.val(i.Width), fe.val(i.S), fe.val(i.I))
	case *ir.MapIterInit:
		e.use("core.map.iterate")
		fe.w("%s = %s.Iter()\n", fe.val(i.Iter), fe.mapVal(i.M))
	case *ir.MapIterNext:
		fe.w("%s, %s, %s = %s.Next()\n", fe.val(i.Ok), fe.assignDst(i.Key), fe.assignDst(i.Val), fe.val(i.Iter))
	case *ir.Print:
		var as []string
		for _, a := range i.Args {
			as = append(as, fe.val(a))
		}
		fn := "print"
		if i.Newline {
			fn = "println"
		}
		fe.w("%s(%s)\n", fn, strings.Join(as, ", "))
	case *ir.Defer:
		if fe.frame {
			fe.frameDefer(i.Call)
			return
		}
		if fe.task {
			fe.nativeDefer(i.Call)
			return
		}
		fe.w("defer %s\n", fe.callExpr(i.Call))
	case *ir.Recover:
		switch {
		case fe.frame:
			fe.w("%s = rt.RecoverFrame(%d)\n", fe.val(i.Dst), fe.f.ID)
		case e.p.Cooperative:
			fe.w("%s = rt.RecoverFrame(%d)\nif %s == nil {\n%s = recover()\n}\n", fe.val(i.Dst), fe.f.ID, fe.val(i.Dst), fe.val(i.Dst))
		default:
			fe.w("%s = recover()\n", fe.val(i.Dst))
		}
	case *ir.Rebind:
		fe.w("{\nn_ := new(%s)\n*n_ = *%s\n%s = n_\n}\n", e.typ(i.L.Type), fe.local(i.L), fe.local(i.L))
	case *ir.BoxParam:
	case *ir.MakeChan:
		e.use("core.chan.make")
		ct := i.Dst.Type.U()
		mk := fmt.Sprintf("rt.MakeChan[%s](%s)", e.typ(ct.Elem), fe.val(i.Size))
		if i.Dst.Type.Kind == ir.KNamed {
			mk = e.typ(i.Dst.Type) + "(" + mk + ")"
		}
		fe.w("%s = %s\n", fe.val(i.Dst), mk)
	case *ir.Close:
		e.use("core.chan.close")
		fe.w("%s.Close()\n", fe.chanVal(i.Ch))
	case *ir.Go:
		e.use("core.task.spawn")
		fe.goStmt(i.Call)
	default:
		panic(fmt.Sprintf("golang: unsupported instruction %T", in))
	}
}

// binExpr renders a non-float binary operation with operator op.
func (fe *fnEmitter) binExpr(i *ir.BinOp, op ir.BinOpKind) string {
	x, y := fe.val(i.X), fe.val(i.Y)
	if c, ok := i.X.(*ir.Const); ok && c.Nil && !nilWrapper(i.X.IRType()) {
		x = "nil"
	}
	if c, ok := i.Y.(*ir.Const); ok && c.Nil && !nilWrapper(i.Y.IRType()) {
		y = "nil"
	}
	return x + " " + op.String() + " " + y
}

// chanVal renders a channel operand as the runtime channel type.
func (fe *fnEmitter) chanVal(v ir.Value) string {
	t := v.IRType()
	if t.Kind == ir.KNamed {
		return "rt.Chan[" + fe.e.typ(t.U().Elem) + "](" + fe.val(v) + ")"
	}
	return fe.val(v)
}

// bindCall binds an evaluated callee and arguments to parameters of a
// function literal, returning the parameter list, the argument list, and
// the call rendered with the bound names.
func (fe *fnEmitter) bindCall(c *ir.Call) (params, args []string, call string) {
	bind := func(v ir.Value, t string) string {
		name := fmt.Sprintf("g%d_", len(params))
		params = append(params, name+" "+t)
		args = append(args, fe.val(v))
		return name
	}
	var sig *ir.Type
	switch c.Kind {
	case ir.CallStatic:
		sig = c.Func.Sig
	case ir.CallValue:
		sig = c.Fn.IRType().U()
	case ir.CallExtern:
		sig = c.Extern.Sig
	default:
		panic("golang: interface call in go or defer")
	}
	var callArgs []string
	for j, a := range c.Args {
		t := a.IRType()
		if j < len(sig.Params) {
			t = sig.Params[j]
		}
		n := bind(a, fe.e.typ(t))
		if sig.Variadic && j == len(c.Args)-1 {
			n += "..."
		}
		callArgs = append(callArgs, n)
	}
	switch c.Kind {
	case ir.CallStatic:
		if fe.e.nativeMethod(c.Func) {
			call = callArgs[0] + "." + fe.e.methodName(c.Func.MethodID, methodShortName(c.Func)) + "(" + strings.Join(callArgs[1:], ", ") + ")"
		} else {
			call = fe.e.names.Symbol(c.Func.Sym) + "(" + strings.Join(callArgs, ", ") + ")"
		}
	case ir.CallValue:
		f := bind(c.Fn, fe.e.typ(c.Fn.IRType()))
		call = f + "(" + strings.Join(callArgs, ", ") + ")"
	case ir.CallExtern:
		fe.e.use(c.Extern.Contract)
		call = fe.e.externSym(c.Extern.Contract) + "(" + strings.Join(callArgs, ", ") + ")"
		if c.Suspends {
			call = "rt.NativeFrame(func(t *rt.Task) { " + fe.e.externSym(c.Extern.Contract) + "(" + strings.Join(append([]string{"t"}, callArgs...), ", ") + ") })"
		}
	}
	return params, args, call
}

// goStmt starts a task running the evaluated call.
func (fe *fnEmitter) goStmt(c *ir.Call) {
	if fe.e.native() && c.Suspends {
		params, args, call := fe.bindTaskCall(c)
		fe.w("func(%s) {\nrt.Spawn(rt.NativeTask(func(t *rt.Task) []any { %s; return nil }))\n}(%s)\n", strings.Join(params, ", "), call, strings.Join(args, ", "))
		return
	}
	params, args, call := fe.bindCall(c)
	frame := call
	if !c.Suspends {
		frame = "rt.Sync(func() []any { " + call + "; return nil })"
	}
	fe.w("func(%s) {\nrt.Spawn(%s)\n}(%s)\n", strings.Join(params, ", "), frame, strings.Join(args, ", "))
}

// bindTaskCall binds an evaluated suspending callee and arguments like
// bindCall; the call takes the task t and waits on runtime primitives.
func (fe *fnEmitter) bindTaskCall(c *ir.Call) (params, args []string, call string) {
	bind := func(v ir.Value, t string) string {
		name := fmt.Sprintf("g%d_", len(params))
		params = append(params, name+" "+t)
		args = append(args, fe.val(v))
		return name
	}
	var sig *ir.Type
	switch c.Kind {
	case ir.CallStatic:
		sig = c.Func.Sig
	case ir.CallValue:
		sig = c.Fn.IRType().U()
	case ir.CallExtern:
		sig = c.Extern.Sig
	default:
		panic("golang: interface call in go or defer")
	}
	callArgs := []string{"t"}
	for j, a := range c.Args {
		t := a.IRType()
		if j < len(sig.Params) {
			t = sig.Params[j]
		}
		n := bind(a, fe.e.typ(t))
		if sig.Variadic && j == len(c.Args)-1 {
			n += "..."
		}
		callArgs = append(callArgs, n)
	}
	switch c.Kind {
	case ir.CallStatic:
		call = fe.e.names.Symbol(c.Func.Sym) + "(" + strings.Join(callArgs, ", ") + ")"
	case ir.CallValue:
		f := bind(c.Fn, fe.e.typ(c.Fn.IRType()))
		call = f + "(" + strings.Join(callArgs, ", ") + ")"
	case ir.CallExtern:
		fe.e.use(c.Extern.Contract)
		call = fe.e.externSym(c.Extern.Contract) + "(" + strings.Join(callArgs, ", ") + "); rt.Wait(t)"
	}
	return params, args, call
}

// nativeDefer defers a call through rt.Defer, which keeps the frame model's
// panic chain and recover identity on the native stack.
func (fe *fnEmitter) nativeDefer(c *ir.Call) {
	params, args, call := fe.bindCall(c)
	if c.Suspends {
		params, args, call = fe.bindTaskCall(c)
	}
	fid := fe.deferFid(c)
	fe.w("defer rt.Defer(t, %d, func(%s) func() { return func() { %s } }(%s))\n", fid, strings.Join(params, ", "), call, strings.Join(args, ", "))
}

func (fe *fnEmitter) deferFid(c *ir.Call) int {
	switch c.Kind {
	case ir.CallStatic:
		return c.Func.ID
	case ir.CallValue:
		if l, ok := c.Fn.(*ir.Local); ok {
			if f := fe.funcOf[l]; f != nil {
				return f.ID
			}
		}
	}
	return -1
}

// frameDefer registers a deferred call on the frame for the runtime to run.
func (fe *fnEmitter) frameDefer(c *ir.Call) {
	params, args, call := fe.bindCall(c)
	fid := -1
	switch c.Kind {
	case ir.CallStatic:
		fid = c.Func.ID
	case ir.CallValue:
		if l, ok := c.Fn.(*ir.Local); ok {
			if f := fe.funcOf[l]; f != nil {
				fid = f.ID
			}
		}
	}
	d := fmt.Sprintf("rt.Deferred{Call: func() { %s }, Fid: %d}", call, fid)
	if c.Suspends {
		d = fmt.Sprintf("rt.Deferred{Start: func() rt.Frame { return %s }, Fid: %d}", call, fid)
	}
	fe.w("fr.Defers = append(fr.Defers, func(%s) rt.Deferred { return %s }(%s))\n", strings.Join(params, ", "), d, strings.Join(args, ", "))
}

// makeBound creates a method value bound to an evaluated receiver.
func (fe *fnEmitter) makeBound(i *ir.MakeBound) {
	e := fe.e
	dt := i.Dst.Type
	if e.nativeMethod(i.Func) && !e.susp(dt) {
		fe.w("%s = %s.%s\n", fe.val(i.Dst), fe.val(i.Recv), e.methodName(i.Func.MethodID, methodShortName(i.Func)))
		return
	}
	u := dt.U()
	ps, as := e.forward(u)
	call := e.funcRef(i.Func) + "(" + strings.Join(append([]string{"r_"}, as...), ", ") + ")"
	var lit string
	switch {
	case e.native() && e.susp(dt):
		recv := []string{"r_"}
		if i.Func.MaySuspend {
			recv = []string{"t", "r_"}
		}
		lit = fmt.Sprintf("func(%s) %s { %s }", strings.Join(append([]string{"t *rt.Task"}, ps...), ", "), syncResults(e, u), nativeBody(len(u.Results), e.funcRef(i.Func)+"("+strings.Join(append(recv, as...), ", ")+")"))
	case e.susp(dt) && i.Func.MaySuspend:
		lit = fmt.Sprintf("func(%s) rt.Frame { return %s }", strings.Join(ps, ", "), call)
	case e.susp(dt):
		lit = fmt.Sprintf("func(%s) rt.Frame { return rt.Sync(func() []any { %s }) }", strings.Join(ps, ", "), syncFrameBody(len(u.Results), call))
	case len(u.Results) == 0:
		lit = fmt.Sprintf("func(%s) { %s }", strings.Join(ps, ", "), call)
	default:
		lit = fmt.Sprintf("func(%s) %s { return %s }", strings.Join(ps, ", "), syncResults(e, u), call)
	}
	fe.w("%s = func(r_ %s) %s { return %s }(%s)\n", fe.val(i.Dst), e.typ(i.Recv.IRType()), e.typ(dt), lit, fe.val(i.Recv))
}

// mapVal renders a map operand as the runtime map type, converting named
// map types, which do not have the runtime's methods.
func (fe *fnEmitter) mapVal(v ir.Value) string {
	t := v.IRType()
	if t.Kind == ir.KNamed {
		u := t.U()
		return "rt.Map[" + fe.e.typ(u.Key) + ", " + fe.e.typ(u.Elem) + "](" + fe.val(v) + ")"
	}
	return fe.val(v)
}

func parenType(t string) string {
	if strings.HasPrefix(t, "*") || strings.HasPrefix(t, "func") || strings.HasPrefix(t, "<-") {
		return "(" + t + ")"
	}
	return t
}

func (fe *fnEmitter) term(t ir.Terminator) {
	switch t := t.(type) {
	case *ir.Jump:
		fe.w("goto b%d\n", t.Target.ID)
	case *ir.If:
		fe.w("if %s {\ngoto b%d\n}\ngoto b%d\n", fe.val(t.Cond), t.Then.ID, t.Else.ID)
	case *ir.Pause:
		fe.pause(t)
	case *ir.Return:
		if fe.frame {
			fe.w("rt.Ret(t, fr)\nreturn\n")
			return
		}
		if hasDefer(fe.f) {
			fe.w("return\n")
			return
		}
		var rs []string
		for _, r := range fe.f.Results {
			rs = append(rs, fe.val(r))
		}
		fe.w("return %s\n", strings.Join(rs, ", "))
	case *ir.Panic:
		fe.w("panic(%s)\n", fe.val(t.X))
	case *ir.PanicRuntime:
		fe.w("panic(rt.PlainError(%q))\n", t.Msg)
	case *ir.Unreachable:
		fe.w("panic(\"goalchemy: unreachable\")\n")
	default:
		panic(fmt.Sprintf("golang: terminator %T", t))
	}
}

// closure emits a function literal for a closure, binding its environment
// to the current storage of the captured variables.
func (fe *fnEmitter) closure(i *ir.MakeClosure) {
	f := i.Func
	e := fe.e
	if f.MaySuspend {
		u := f.Sig.U()
		var envPs, envAs, call []string
		for j, l := range f.Env {
			envPs = append(envPs, fmt.Sprintf("e%d_ *%s", j, e.typ(l.Type)))
			envAs = append(envAs, fe.local(i.Env[j]))
			call = append(call, fmt.Sprintf("e%d_", j))
		}
		ps, as := e.forward(u)
		call = append(call, as...)
		if e.native() {
			fe.w("%s = func(%s) %s { return func(%s) %s { %s } }(%s)\n", fe.val(i.Dst), strings.Join(envPs, ", "),
				e.startType(u), strings.Join(append([]string{"t *rt.Task"}, ps...), ", "), syncResults(e, u), nativeBody(len(u.Results), fe.e.names.Symbol(f.Sym)+"("+strings.Join(append([]string{"t"}, call...), ", ")+")"), strings.Join(envAs, ", "))
			return
		}
		fe.w("%s = func(%s) %s { return func(%s) rt.Frame { return %s(%s) } }(%s)\n", fe.val(i.Dst), strings.Join(envPs, ", "),
			e.startType(u), strings.Join(ps, ", "), fe.e.names.Symbol(f.Sym), strings.Join(call, ", "), strings.Join(envAs, ", "))
		return
	}
	ce := fe.e.localNames(f)
	var body bytes.Buffer
	ce.b = &body
	ce.body()
	var envParams, envArgs []string
	for j, l := range f.Env {
		envParams = append(envParams, ce.local(l)+" *"+fe.e.typ(l.Type))
		envArgs = append(envArgs, fe.local(i.Env[j]))
	}
	if e.susp(i.Dst.Type) {
		fe.w("%s = %s\n", fe.val(i.Dst), e.adapt(i.Dst.Type, fmt.Sprintf("func(%s) %s {\nreturn func%s {\n%s}\n}(%s)",
			strings.Join(envParams, ", "), e.syncType(f.Sig), e.signature(f, ce, false), body.String(), strings.Join(envArgs, ", "))))
		return
	}
	fe.w("%s = func(%s) %s {\nreturn func%s {\n", fe.val(i.Dst), strings.Join(envParams, ", "), fe.e.typ(f.Sig), fe.e.signature(f, ce, false))
	fe.b.Write(body.Bytes())
	fe.w("}\n}(%s)\n", strings.Join(envArgs, ", "))
}

func hasDefer(f *ir.Func) bool {
	for _, b := range f.Blocks {
		for _, in := range b.Instrs {
			if _, ok := in.(*ir.Defer); ok {
				return true
			}
		}
	}
	return false
}
